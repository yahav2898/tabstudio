using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using TabStudio.Compilation.Wpf;

namespace TabStudio.Wpf.Browser;

/// <summary>
/// The C# of a WPF app's browser host, the program the browser runs, as OpenSilver's <c>.Browser</c> project is for an
/// OpenSilver app: Blazor's WebAssembly host with a component that starts the app through OpenSilver's runner, the way
/// WPF starts it, and shows its first window in the page.
/// </summary>
internal static class BrowserHostSource
{
    /// <summary>The namespace of the host's types.</summary>
    public const string Namespace = "TabStudio.WpfHost";

    /// <summary>The C# of the host.</summary>
    /// <param name="appName">The app's project name, for the messages.</param>
    /// <param name="appAssemblyName">The app's assembly.</param>
    /// <param name="startup">How the app starts.</param>
    public static string Create(string appName, string appAssemblyName, WpfStartupInfo startup)
    {
        ArgumentNullException.ThrowIfNull(startup);
        var startupWindow = startup.StartupUri is { } uri ? startup.WindowAt(uri) : null;
        var windows = new StringBuilder();
        foreach (var window in startup.Windows.Where(w => w.CanCreate))
        {
            windows.Append(CultureInfo.InvariantCulture, $"            [{Literal(window.RelativePath)}] = () => new global::{window.ClassName}(),\n");
        }

        var backgrounds = new StringBuilder();
        foreach (var window in startup.Windows.Where(w => w.Background is not null))
        {
            backgrounds.Append(CultureInfo.InvariantCulture, $"            [{Literal(window.ClassName)}] = {Literal(window.Background!)},\n");
        }

        var source = new StringBuilder();
        source.Append(CultureInfo.InvariantCulture, $$"""
            // <auto-generated>
            //     TabStudio's browser host for the WPF app {{appName}}, which runs on OpenSilver: what OpenSilver's .Browser
            //     project is for an OpenSilver app, with the startup WPF gives an app.
            // </auto-generated>

            #nullable enable

            namespace {{Namespace}}
            {
                /// <summary>Starts Blazor's WebAssembly host, which OpenSilver's scripts talk to .NET through.</summary>
                public static class Program
                {
                    /// <summary>The browser's entry point.</summary>
                    /// <param name="args">The arguments.</param>
                    public static async global::System.Threading.Tasks.Task Main(string[] args)
                    {
                        var builder = global::Microsoft.AspNetCore.Components.WebAssembly.Hosting.WebAssemblyHostBuilder.CreateDefault(args);
                        builder.RootComponents.Add<Root>("#app");
                        await builder.Build().RunAsync();
                    }
                }

                /// <summary>The component that starts the app once Blazor is up, as OpenSilver's Index page does.</summary>
                public sealed class Root : global::Microsoft.AspNetCore.Components.ComponentBase
                {
                    /// <inheritdoc />
                    protected override async global::System.Threading.Tasks.Task OnInitializedAsync()
                    {
                        await base.OnInitializedAsync();
                        await global::OpenSilver.WebAssembly.Runner.RunApplicationAsync(WpfApp.Start);
                    }
                }

                /// <summary>Starts the WPF app as WPF does, and shows its first window in the page.</summary>
                internal static class WpfApp
                {
                    private const string AppName = {{Literal(appName)}};

                    /// <summary>The window App.xaml's StartupUri opens, by its XAML file, if any.</summary>
                    private static readonly string? StartupWindow = {{(startupWindow is null ? "null" : Literal(startupWindow.RelativePath))}};

                    private static readonly global::System.Collections.Generic.Dictionary<string, global::System.Func<global::System.Windows.Window>> Windows =
                        new(global::System.StringComparer.OrdinalIgnoreCase)
                        {
            {{windows}}            };

                    private static readonly global::System.Collections.Generic.Dictionary<string, string> Backgrounds =
                        new(global::System.StringComparer.Ordinal)
                        {
            {{backgrounds}}            };

                    private static global::System.Windows.Window? _shown;
                    private static string? _title;
                    private static int _attempts;

                    /// <summary>Runs the app's entry point, which creates the application and loads App.xaml.</summary>
                    public static global::System.Windows.Application Start()
                    {
                        global::System.AppDomain.CurrentDomain.UnhandledException += (_, e) => Report(e.ExceptionObject);
                        global::System.Threading.Tasks.TaskScheduler.UnobservedTaskException += (_, e) => { Report(e.Exception); e.SetObserved(); };

                        var assembly = global::System.Reflection.Assembly.Load({{Literal(appAssemblyName)}});
                        var entryPoint = assembly.EntryPoint ?? throw new global::System.InvalidOperationException(AppName + " has no Main method to start it with. A WPF app's App.xaml is its ApplicationDefinition, which gives it one.");
                        try
                        {
                            entryPoint.Invoke(null, entryPoint.GetParameters().Length == 0 ? null : new object?[] { global::System.Array.Empty<string>() });
                        }
                        catch (global::System.Reflection.TargetInvocationException ex) when (ex.InnerException is { } inner)
                        {
                            global::System.Runtime.ExceptionServices.ExceptionDispatchInfo.Capture(inner).Throw();
                        }

                        var app = global::System.Windows.Application.Current
                            ?? throw new global::System.InvalidOperationException(AppName + "'s Main did not create its application.");
                        app.UnhandledException += (_, e) =>
                        {
                            if (!e.Handled)
                            {
                                Report(e.ExceptionObject);
                                e.Handled = true;
                                if (_shown is { } shown)
                                {
                                    ReleaseInputCapture(shown);
                                }
                            }
                        };

                        // After the application's own startup, which OpenSilver runs on the dispatcher, as WPF opens StartupUri after Startup.
                        global::System.Windows.Threading.Dispatcher.CurrentDispatcher.BeginInvoke(() => ShowStartupWindow(app));
                        return app;
                    }

                    /// <summary>Releases capture left behind when OpenSilver's input handler unwinds before its cleanup.</summary>
                    private static bool ReleaseInputCapture(global::System.Windows.DependencyObject root)
                    {
                        if (root is global::System.Windows.UIElement { IsMouseCaptured: true } element)
                        {
                            element.ReleaseMouseCapture();
                            return true;
                        }

                        for (var i = 0; i < global::System.Windows.Media.VisualTreeHelper.GetChildrenCount(root); i++)
                        {
                            if (ReleaseInputCapture(global::System.Windows.Media.VisualTreeHelper.GetChild(root, i)))
                            {
                                return true;
                            }
                        }

                        return false;
                    }

                    private static void ShowStartupWindow(global::System.Windows.Application app)
                    {
                        var window = global::System.AppContext.GetData({{Literal(WpfXamlGenerator.MainWindowKey)}}) as global::System.Windows.Window;
                        if (window is null && StartupWindow is { } startupWindow)
                        {
                            window = Create(startupWindow);
                        }

                        window ??= FirstWindow(app);
                        if (window is null)
                        {
                            if (++_attempts < 20)
                            {
                                // The app's startup may still be on its way, as after an await in OnStartup.
                                var timer = new global::System.Windows.Threading.DispatcherTimer { Interval = global::System.TimeSpan.FromMilliseconds(250) };
                                timer.Tick += (_, _) => { timer.Stop(); ShowStartupWindow(app); };
                                timer.Start();
                                return;
                            }

                            global::System.Console.Error.WriteLine({{Literal(startup.StartupUri is string missing && startupWindow is null
                                ? $"{appName} has no window to show: App.xaml's StartupUri is \"{missing}\", which is not a window of the project with a public parameterless constructor."
                                : $"{appName} has no window to show: set StartupUri in App.xaml, or create a window in OnStartup.")}});
                            return;
                        }

                        Show(window);
                    }

                    private static global::System.Windows.Window? Create(string path) =>
                        Windows.TryGetValue(path, out var create) ? create() : null;

                    private static global::System.Windows.Window? FirstWindow(global::System.Windows.Application app)
                    {
                        foreach (var item in app.Windows)
                        {
                            if (item is global::System.Windows.Window window && !ReferenceEquals(window, app.MainWindow))
                            {
                                return window;
                            }
                        }

                        return null;
                    }

                    /// <summary>Puts a window in the page, filling it below TabStudio's title bar, as the app's main window.</summary>
                    private static void Show(global::System.Windows.Window window)
                    {
                        _shown = window;
                        window.ClearValue(global::System.Windows.FrameworkElement.WidthProperty);
                        window.ClearValue(global::System.Windows.FrameworkElement.HeightProperty);
                        if (Backgrounds.TryGetValue(window.GetType().FullName ?? string.Empty, out var background))
                        {
                            Call("setBackground", background);
                        }

                        window.AttachToDomElement(new global::CSHTML5.Internal.INTERNAL_HtmlDomElementReference("tabstudio-wpf-client"));
                        global::System.Windows.Window.Current = window;
                        BecomeMainWindow(window);

                        // OpenSilver lays a window out when its content is set after it is in the page; this window's
                        // content was set by InitializeComponent before, so it is laid out here, at the page's size.
                        var bounds = window.Bounds;
                        window.InvalidateMeasure();
                        window.Measure(bounds.Size);
                        window.Arrange(bounds);
                        window.UpdateLayout();
                        UpdateTitle();
                        var timer = new global::System.Windows.Threading.DispatcherTimer { Interval = global::System.TimeSpan.FromMilliseconds(500) };
                        timer.Tick += (_, _) => UpdateTitle();
                        timer.Start();
                    }

                    /// <summary>
                    /// Makes the window the application's MainWindow, as WPF makes the first window it opens: OpenSilver's
                    /// own main window stays out of sight, where it measures text.
                    /// </summary>
                    private static void BecomeMainWindow(global::System.Windows.Window window)
                    {
                        var field = typeof(global::System.Windows.Application).GetField("_mainWindow", global::System.Reflection.BindingFlags.Instance | global::System.Reflection.BindingFlags.NonPublic);
                        if (field is not null && field.FieldType == typeof(global::System.Windows.Window) && global::System.Windows.Application.Current is { } app)
                        {
                            field.SetValue(app, window);
                        }
                    }

                    private static void UpdateTitle()
                    {
                        var title = _shown?.Title;
                        if (string.IsNullOrEmpty(title))
                        {
                            title = AppName;
                        }

                        if (title != _title)
                        {
                            _title = title;
                            Call("setTitle", title);
                        }
                    }

                    private static void Call(string function, string argument) =>
                        global::OpenSilver.Interop.ExecuteJavaScriptVoid("window.tabStudioWpf." + function + "(" + global::System.Text.Json.JsonSerializer.Serialize(argument) + ")");

                    private static void Report(object exception) =>
                        global::System.Console.Error.WriteLine("Unhandled exception in " + AppName + ": " + exception);
                }
            }

            """);
        return source.ToString();
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
