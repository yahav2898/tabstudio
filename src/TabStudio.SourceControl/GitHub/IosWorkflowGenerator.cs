using System.Text.Json;

namespace TabStudio.SourceControl.GitHub;

/// <summary>A repository secret needed by the signed iOS workflow.</summary>
public sealed record IosBuildSecret(string Name, string Explanation);

/// <summary>The repository-relative iOS project and shared Xcode scheme.</summary>
public sealed record IosWorkflowOptions(bool Capacitor, string ProjectDirectory = ".", string XcodeProject = "ios/App/App.xcworkspace", string Scheme = "App");

/// <summary>Generates a reviewable, dispatch-only macOS build with signing, IPA artifacts and optional TestFlight.</summary>
public static class IosWorkflowGenerator
{
    /// <summary>The workflow's stable repository path.</summary>
    public const string WorkflowPath = ".github/workflows/tabstudio-ios.yml";

    /// <summary>Descriptions shown in the IDE and in the generated setup guide.</summary>
    public static IReadOnlyList<IosBuildSecret> Secrets { get; } =
    [
        new("ASC_KEY_ID", "App Store Connect API key ID, from Users and Access > Integrations > App Store Connect API. Use a key with access to this app and TestFlight."),
        new("ASC_ISSUER_ID", "Issuer ID shown beside the App Store Connect API keys."),
        new("ASC_PRIVATE_KEY", "The complete contents of the downloaded AuthKey_….p8 private key, including its BEGIN and END lines."),
        new("IOS_CERTIFICATE_P12_BASE64", "Base64 of an Apple Distribution signing certificate and its private key exported together as a .p12 file."),
        new("IOS_CERTIFICATE_PASSWORD", "Password protecting that .p12 file."),
        new("IOS_PROVISION_PROFILE_BASE64", "Base64 of an App Store distribution .mobileprovision profile matching the certificate, team and bundle ID."),
        new("IOS_TEAM_ID", "The 10-character Apple Developer team ID."),
        new("IOS_BUNDLE_ID", "The exact application bundle identifier, matching Xcode, the profile and the app in App Store Connect."),
    ];

    /// <summary>Creates the YAML. Values from project names are passed through environment variables, never shell source.</summary>
    public static string Generate(IosWorkflowOptions options)
    {
        ArgumentNullException.ThrowIfNull(options);
        ValidateRelative(options.ProjectDirectory);
        ValidateRelative(options.XcodeProject);
        if (string.IsNullOrWhiteSpace(options.Scheme) || options.Scheme.Any(char.IsControl))
        {
            throw new ArgumentException("Use the name of a shared Xcode scheme.", nameof(options));
        }

        var prepare = options.Capacitor ? """
              - uses: actions/setup-node@v4
                with:
                  node-version: '22'
              - name: Build and sync the Capacitor web app
                shell: bash
                run: |
                  set -euo pipefail
                  cd "$PROJECT_DIRECTORY"
                  if [ -f package-lock.json ]; then npm ci; else npm install; fi
                  npm run build
                  if [ ! -d ios ]; then npx --no-install cap add ios; fi
                  npx --no-install cap sync ios
            """ : """
              - name: Resolve native project dependencies
                shell: bash
                run: |
                  set -euo pipefail
                  cd "$PROJECT_DIRECTORY"
                  if [ -f Podfile ]; then pod install; fi
            """;

        return $$$"""
            # Generated by TabStudio. Review, commit and push this file before running it.
            # No local Mac is needed. An Apple Developer account, signing assets and repository secrets are required.
            name: Build for iOS
            on:
              workflow_dispatch:
                inputs:
                  upload_to_testflight:
                    description: Upload the signed IPA to TestFlight
                    type: boolean
                    default: false
            permissions:
              contents: read
            concurrency:
              group: ios-${{ github.ref }}
              cancel-in-progress: false
            jobs:
              ios:
                runs-on: macos-15
                timeout-minutes: 45
                env:
                  PROJECT_DIRECTORY: {{{JsonSerializer.Serialize(options.ProjectDirectory)}}}
                  XCODE_PROJECT: {{{JsonSerializer.Serialize(options.XcodeProject)}}}
                  XCODE_SCHEME: {{{JsonSerializer.Serialize(options.Scheme)}}}
                  ASC_KEY_ID: ${{ secrets.ASC_KEY_ID }}
                  ASC_ISSUER_ID: ${{ secrets.ASC_ISSUER_ID }}
                  ASC_PRIVATE_KEY: ${{ secrets.ASC_PRIVATE_KEY }}
                  IOS_CERTIFICATE_P12_BASE64: ${{ secrets.IOS_CERTIFICATE_P12_BASE64 }}
                  IOS_CERTIFICATE_PASSWORD: ${{ secrets.IOS_CERTIFICATE_PASSWORD }}
                  IOS_PROVISION_PROFILE_BASE64: ${{ secrets.IOS_PROVISION_PROFILE_BASE64 }}
                  IOS_TEAM_ID: ${{ secrets.IOS_TEAM_ID }}
                  IOS_BUNDLE_ID: ${{ secrets.IOS_BUNDLE_ID }}
                steps:
                  - uses: actions/checkout@v4
            {{{Indent(prepare, 4)}}}
                  - name: Import signing assets into a temporary keychain
                    shell: bash
                    run: |
                      set -euo pipefail
                      for name in ASC_KEY_ID ASC_ISSUER_ID ASC_PRIVATE_KEY IOS_CERTIFICATE_P12_BASE64 IOS_CERTIFICATE_PASSWORD IOS_PROVISION_PROFILE_BASE64 IOS_TEAM_ID IOS_BUNDLE_ID; do
                        if [ -z "${!name}" ]; then echo "::error::Add repository secret $name (see docs/IOS-BUILD.md)"; exit 1; fi
                      done
                      keychain="$RUNNER_TEMP/tabstudio-ios.keychain-db"
                      password=$(openssl rand -hex 24)
                      security create-keychain -p "$password" "$keychain"
                      security set-keychain-settings -lut 21600 "$keychain"
                      security unlock-keychain -p "$password" "$keychain"
                      python3 - <<'PY'
                      import base64, os, pathlib
                      root = pathlib.Path(os.environ['RUNNER_TEMP'])
                      (root / 'distribution.p12').write_bytes(base64.b64decode(os.environ['IOS_CERTIFICATE_P12_BASE64'], validate=True))
                      (root / 'profile.mobileprovision').write_bytes(base64.b64decode(os.environ['IOS_PROVISION_PROFILE_BASE64'], validate=True))
                      (root / ('AuthKey_' + os.environ['ASC_KEY_ID'] + '.p8')).write_text(os.environ['ASC_PRIVATE_KEY'])
                      PY
                      security import "$RUNNER_TEMP/distribution.p12" -P "$IOS_CERTIFICATE_PASSWORD" -A -t cert -f pkcs12 -k "$keychain"
                      security set-key-partition-list -S apple-tool:,apple:,codesign: -s -k "$password" "$keychain"
                      security list-keychains -d user -s "$keychain" "$HOME/Library/Keychains/login.keychain-db"
                      security cms -D -i "$RUNNER_TEMP/profile.mobileprovision" > "$RUNNER_TEMP/profile.plist"
                      python3 - <<'PY'
                      import os, pathlib, plistlib
                      root = pathlib.Path(os.environ['RUNNER_TEMP'])
                      profile = plistlib.loads((root / 'profile.plist').read_bytes())
                      if os.environ['IOS_TEAM_ID'] not in profile['TeamIdentifier']: raise SystemExit('Profile team does not match IOS_TEAM_ID')
                      app_id = profile['Entitlements']['application-identifier']
                      if app_id != os.environ['IOS_TEAM_ID'] + '.' + os.environ['IOS_BUNDLE_ID']: raise SystemExit('Profile does not match IOS_BUNDLE_ID')
                      for relative in ('Library/Developer/Xcode/UserData/Provisioning Profiles', 'Library/MobileDevice/Provisioning Profiles'):
                          folder = pathlib.Path.home() / relative
                          folder.mkdir(parents=True, exist_ok=True)
                          (folder / (profile['UUID'] + '.mobileprovision')).write_bytes((root / 'profile.mobileprovision').read_bytes())
                      options = {'method':'app-store-connect', 'teamID':os.environ['IOS_TEAM_ID'], 'signingStyle':'manual', 'signingCertificate':'Apple Distribution', 'provisioningProfiles':{os.environ['IOS_BUNDLE_ID']:profile['UUID']}}
                      (root / 'ExportOptions.plist').write_bytes(plistlib.dumps(options))
                      PY
                  - name: Archive and export the IPA
                    shell: bash
                    run: |
                      set -euo pipefail
                      cd "$PROJECT_DIRECTORY"
                      kind=-project
                      if [[ "$XCODE_PROJECT" == *.xcworkspace ]]; then kind=-workspace; fi
                      key="$RUNNER_TEMP/AuthKey_${ASC_KEY_ID}.p8"
                      xcodebuild "$kind" "$XCODE_PROJECT" -scheme "$XCODE_SCHEME" -configuration Release \
                        -destination 'generic/platform=iOS' -archivePath "$RUNNER_TEMP/App.xcarchive" \
                        -allowProvisioningUpdates -authenticationKeyPath "$key" -authenticationKeyID "$ASC_KEY_ID" -authenticationKeyIssuerID "$ASC_ISSUER_ID" \
                        DEVELOPMENT_TEAM="$IOS_TEAM_ID" CODE_SIGN_STYLE=Automatic archive
                      xcodebuild -exportArchive -archivePath "$RUNNER_TEMP/App.xcarchive" \
                        -exportOptionsPlist "$RUNNER_TEMP/ExportOptions.plist" -exportPath "$RUNNER_TEMP/ipa"
                  - uses: actions/upload-artifact@v4
                    with:
                      name: iOS-IPA
                      path: ${{ runner.temp }}/ipa/*.ipa
                      if-no-files-found: error
                  - name: Upload to TestFlight
                    if: ${{ inputs.upload_to_testflight }}
                    shell: bash
                    run: |
                      set -euo pipefail
                      mkdir -p "$HOME/.appstoreconnect/private_keys"
                      cp "$RUNNER_TEMP/AuthKey_${ASC_KEY_ID}.p8" "$HOME/.appstoreconnect/private_keys/"
                      ipa=$(find "$RUNNER_TEMP/ipa" -name '*.ipa' -print -quit)
                      xcrun altool --upload-app --type ios --file "$ipa" --apiKey "$ASC_KEY_ID" --apiIssuer "$ASC_ISSUER_ID"
                  - name: Remove signing assets
                    if: always()
                    shell: bash
                    run: |
                      security delete-keychain "$RUNNER_TEMP/tabstudio-ios.keychain-db" || true
                      rm -f "$RUNNER_TEMP/distribution.p12" "$RUNNER_TEMP/profile.mobileprovision" "$RUNNER_TEMP/profile.plist" "$RUNNER_TEMP"/AuthKey_*.p8
                      rm -f "$HOME/.appstoreconnect/private_keys/AuthKey_${ASC_KEY_ID}.p8"
                      rm -f "$HOME/Library/MobileDevice/Provisioning Profiles/"*.mobileprovision
                      rm -f "$HOME/Library/Developer/Xcode/UserData/Provisioning Profiles/"*.mobileprovision
            """ + "\n";
    }

    /// <summary>A guide shown beside the generated workflow, with every repository secret explained.</summary>
    public static string SetupGuide() => """
        # Build for iOS from TabStudio

        A Mac is never needed locally: GitHub's macOS runner builds and signs the app. An active paid Apple
        Developer account is required for signing and TestFlight, along with an App Store Connect app record.
        GitHub Actions runner minutes may have a cost. Native projects need a shared Xcode scheme.

        1. Review `.github/workflows/tabstudio-ios.yml`, especially PROJECT_DIRECTORY, XCODE_PROJECT and XCODE_SCHEME.
        2. In the repository on GitHub, open Settings > Secrets and variables > Actions. Add these repository secrets:

        """ + string.Join("\n", Secrets.Select(s => $"- **{s.Name}**: {s.Explanation}")) + "\n\n" + """
        You can generate a certificate signing request and private key with OpenSSL on the tablet, submit the CSR
        under Certificates in Apple's developer portal, then combine the issued distribution certificate and
        private key into a password-protected PKCS#12 (.p12). Create the matching App Store provisioning profile
        in that portal. Base64-encode the .p12 and profile without line breaks. Never commit any signing assets.

        Commit and push the workflow and guide using Git Changes. GitHub must have the workflow on the default
        branch before it can be dispatched; merge your workflow PR if necessary. Choose Build > Run iOS Workflow
        to open the existing Actions run form on this repository's branch. Select upload_to_testflight only when
        you want an upload. The Actions window shows progress, job logs and the iOS-IPA download artifact.

        Capacitor projects install npm packages, build the web part, add iOS if necessary, and sync it on the runner.
        Native Xcode projects resolve a root Podfile when present. Projects with other dependency setup can add it
        to the generated workflow. Set a new CFBundleVersion for each TestFlight upload. TestFlight processing and
        external tester review happen in App Store Connect after upload.
        """ + "\n";

    private static string Indent(string text, int count) => string.Join('\n', text.Split('\n').Select(l => new string(' ', count) + l));

    private static void ValidateRelative(string path)
    {
        if (string.IsNullOrWhiteSpace(path) || Path.IsPathRooted(path) || path.Contains('\\') || path.Any(char.IsControl)
            || path.Split('/').Any(p => p == "..") || path.Contains(':', StringComparison.Ordinal))
        {
            throw new ArgumentException("Use a repository-relative project path without parent traversal.", nameof(path));
        }
    }
}
