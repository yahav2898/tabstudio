using TsProject = TabStudio.Core.Workspaces.ProjectInfo;

namespace TabStudio.Compilation.VisualBasic;

/// <summary>
/// <c>My.Settings</c> for Visual Basic projects: the <c>MySettings</c> class Visual Studio's settings designer writes
/// into <c>My Project/Settings.Designer.vb</c> derives from <c>System.Configuration.ApplicationSettingsBase</c>, which
/// the Windows desktop has and this device does not. As <see cref="DesktopSettings"/> does for C#, TabStudio compiles
/// such a project with a small <c>ApplicationSettingsBase</c> of its own, written in Visual Basic and <c>Friend</c> to
/// the project: a setting starts with its <c>DefaultSettingValue</c> and keeps what the app sets while it runs.
/// </summary>
public static class VisualBasicSettings
{
    /// <summary>The file name of the generated settings class Visual Studio's settings designer writes.</summary>
    public const string SettingsDesignerFileName = "Settings.Designer.vb";

    /// <summary>
    /// Whether a project gets TabStudio's <c>ApplicationSettingsBase</c>: a Visual Basic project that compiles a
    /// <c>Settings.Designer.vb</c> and does not reference the package that has the real one.
    /// </summary>
    /// <param name="project">The project.</param>
    /// <param name="sourceFiles">The source files it compiles.</param>
    public static bool Applies(TsProject project, IEnumerable<string> sourceFiles)
    {
        ArgumentNullException.ThrowIfNull(project);
        ArgumentNullException.ThrowIfNull(sourceFiles);
        return project.IsVisualBasic
            && !project.HasPackage("System.Configuration.ConfigurationManager")
            && sourceFiles.Any(f => string.Equals(Path.GetFileName(f), SettingsDesignerFileName, StringComparison.OrdinalIgnoreCase));
    }

    /// <summary>The Visual Basic source of TabStudio's <c>System.Configuration</c> settings types.</summary>
    public const string Source = """
        ' <auto-generated>
        '     Generated by TabStudio: the System.Configuration settings types that My Project/Settings.Designer.vb uses,
        '     for a Visual Basic app that runs on this device. Settings start with their default values and keep what
        '     the app sets while it runs.
        ' </auto-generated>
        Option Strict On
        Option Explicit On

        Namespace Global.System.Configuration

            Friend Enum SpecialSetting
                ConnectionString
                WebServiceUrl
            End Enum

            Friend Enum SettingsSerializeAs
                [String]
                Xml
                Binary
                ProviderSpecific
            End Enum

            Friend Enum SettingsManageability
                Roaming
            End Enum

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property)>
            Friend NotInheritable Class UserScopedSettingAttribute
                Inherits Global.System.Attribute
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property)>
            Friend NotInheritable Class ApplicationScopedSettingAttribute
                Inherits Global.System.Attribute
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property)>
            Friend NotInheritable Class DefaultSettingValueAttribute
                Inherits Global.System.Attribute

                Public Sub New(value As String)
                    Me.Value = value
                End Sub

                Public ReadOnly Property Value As String
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property Or Global.System.AttributeTargets.Class)>
            Friend NotInheritable Class SpecialSettingAttribute
                Inherits Global.System.Attribute

                Public Sub New(specialSetting As SpecialSetting)
                    Me.SpecialSetting = specialSetting
                End Sub

                Public ReadOnly Property SpecialSetting As SpecialSetting
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property Or Global.System.AttributeTargets.Class)>
            Friend NotInheritable Class SettingsSerializeAsAttribute
                Inherits Global.System.Attribute

                Public Sub New(serializeAs As SettingsSerializeAs)
                    Me.SerializeAs = serializeAs
                End Sub

                Public ReadOnly Property SerializeAs As SettingsSerializeAs
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property Or Global.System.AttributeTargets.Class)>
            Friend NotInheritable Class SettingsDescriptionAttribute
                Inherits Global.System.Attribute

                Public Sub New(description As String)
                    Me.Description = description
                End Sub

                Public ReadOnly Property Description As String
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property Or Global.System.AttributeTargets.Class)>
            Friend NotInheritable Class SettingsGroupNameAttribute
                Inherits Global.System.Attribute

                Public Sub New(groupName As String)
                    Me.GroupName = groupName
                End Sub

                Public ReadOnly Property GroupName As String
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property Or Global.System.AttributeTargets.Class)>
            Friend NotInheritable Class SettingsManageabilityAttribute
                Inherits Global.System.Attribute

                Public Sub New(manageability As SettingsManageability)
                    Me.Manageability = manageability
                End Sub

                Public ReadOnly Property Manageability As SettingsManageability
            End Class

            <Global.System.AttributeUsage(Global.System.AttributeTargets.Property Or Global.System.AttributeTargets.Class)>
            Friend NotInheritable Class NoSettingsVersionUpgradeAttribute
                Inherits Global.System.Attribute
            End Class

            Friend Class SettingChangingEventArgs
                Inherits Global.System.ComponentModel.CancelEventArgs

                Public Sub New(settingName As String, settingClass As String, settingKey As String, newValue As Object, cancel As Boolean)
                    MyBase.New(cancel)
                    Me.SettingName = settingName
                    Me.SettingClass = settingClass
                    Me.SettingKey = settingKey
                    Me.NewValue = newValue
                End Sub

                Public ReadOnly Property SettingName As String
                Public ReadOnly Property SettingClass As String
                Public ReadOnly Property SettingKey As String
                Public ReadOnly Property NewValue As Object
            End Class

            Friend Delegate Sub SettingChangingEventHandler(sender As Object, e As SettingChangingEventArgs)

            Friend Class SettingsLoadedEventArgs
                Inherits Global.System.EventArgs
            End Class

            Friend Delegate Sub SettingsLoadedEventHandler(sender As Object, e As SettingsLoadedEventArgs)

            Friend Delegate Sub SettingsSavingEventHandler(sender As Object, e As Global.System.ComponentModel.CancelEventArgs)

            Friend MustInherit Class SettingsBase
                Private ReadOnly _values As New Global.System.Collections.Generic.Dictionary(Of String, Object)()

                Default Public Overridable Property Item(propertyName As String) As Object
                    Get
                        SyncLock _values
                            Dim value As Object = Nothing
                            If Not _values.TryGetValue(propertyName, value) Then
                                value = DefaultValue(propertyName)
                                _values(propertyName) = value
                            End If

                            Return value
                        End SyncLock
                    End Get
                    Set(value As Object)
                        SyncLock _values
                            _values(propertyName) = value
                        End SyncLock
                    End Set
                End Property

                Public ReadOnly Property IsSynchronized As Boolean
                    Get
                        Return True
                    End Get
                End Property

                Public Shared Function Synchronized(settingsBase As SettingsBase) As SettingsBase
                    Return settingsBase
                End Function

                Public Overridable Sub Save()
                End Sub

                ''' <summary>Forgets what the app set, so every setting has its default value again.</summary>
                Protected Sub Clear()
                    SyncLock _values
                        _values.Clear()
                    End SyncLock
                End Sub

                Private Function DefaultValue(propertyName As String) As Object
                    Dim [property] = Me.GetType().GetProperty(propertyName, Global.System.Reflection.BindingFlags.Instance Or Global.System.Reflection.BindingFlags.Public Or Global.System.Reflection.BindingFlags.NonPublic)
                    If [property] Is Nothing Then
                        Return Nothing
                    End If

                    Dim type = [property].PropertyType
                    Dim attribute = TryCast(Global.System.Attribute.GetCustomAttribute([property], GetType(DefaultSettingValueAttribute)), DefaultSettingValueAttribute)
                    If attribute Is Nothing Then
                        Return If(type.IsValueType, Global.System.Activator.CreateInstance(type), Nothing)
                    End If

                    If type Is GetType(String) Then
                        Return attribute.Value
                    End If

                    Try
                        Return Global.System.ComponentModel.TypeDescriptor.GetConverter(type).ConvertFromInvariantString(attribute.Value)
                    Catch ex As Global.System.Exception
                        Return If(type.IsValueType, Global.System.Activator.CreateInstance(type), Nothing)
                    End Try
                End Function
            End Class

            Friend MustInherit Class ApplicationSettingsBase
                Inherits SettingsBase
                Implements Global.System.ComponentModel.INotifyPropertyChanged

                Protected Sub New()
                End Sub

                Protected Sub New(settingsKey As String)
                    Me.SettingsKey = settingsKey
                End Sub

                Public Event PropertyChanged As Global.System.ComponentModel.PropertyChangedEventHandler Implements Global.System.ComponentModel.INotifyPropertyChanged.PropertyChanged

                Public Event SettingChanging As SettingChangingEventHandler

                Public Event SettingsLoaded As SettingsLoadedEventHandler

                Public Event SettingsSaving As SettingsSavingEventHandler

                Public Property SettingsKey As String = String.Empty

                Default Public Overrides Property Item(propertyName As String) As Object
                    Get
                        Return MyBase.Item(propertyName)
                    End Get
                    Set(value As Object)
                        Dim changing As New SettingChangingEventArgs(propertyName, Me.GetType().FullName, SettingsKey, value, False)
                        OnSettingChanging(Me, changing)
                        If Not changing.Cancel Then
                            MyBase.Item(propertyName) = value
                            OnPropertyChanged(Me, New Global.System.ComponentModel.PropertyChangedEventArgs(propertyName))
                        End If
                    End Set
                End Property

                Public Function GetPreviousVersion(propertyName As String) As Object
                    Return Nothing
                End Function

                Public Sub Reload()
                    RaiseEvent SettingsLoaded(Me, New SettingsLoadedEventArgs())
                End Sub

                Public Sub Reset()
                    Clear()
                End Sub

                Public Overrides Sub Save()
                    OnSettingsSaving(Me, New Global.System.ComponentModel.CancelEventArgs())
                End Sub

                Public Overridable Sub Upgrade()
                End Sub

                Protected Overridable Sub OnPropertyChanged(sender As Object, e As Global.System.ComponentModel.PropertyChangedEventArgs)
                    RaiseEvent PropertyChanged(sender, e)
                End Sub

                Protected Overridable Sub OnSettingChanging(sender As Object, e As SettingChangingEventArgs)
                    RaiseEvent SettingChanging(sender, e)
                End Sub

                Protected Overridable Sub OnSettingsLoaded(sender As Object, e As SettingsLoadedEventArgs)
                    RaiseEvent SettingsLoaded(sender, e)
                End Sub

                Protected Overridable Sub OnSettingsSaving(sender As Object, e As Global.System.ComponentModel.CancelEventArgs)
                    RaiseEvent SettingsSaving(sender, e)
                End Sub
            End Class
        End Namespace
        """;
}
