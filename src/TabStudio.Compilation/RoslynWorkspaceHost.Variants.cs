using System.Diagnostics;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using TsProject = TabStudio.Core.Workspaces.ProjectInfo;

namespace TabStudio.Compilation;

/// <summary>A C# file a build step outside Roslyn generated, such as a WPF page's partial class.</summary>
/// <param name="Path">Where the build step wrote it, under the project's <c>obj</c> folder.</param>
/// <param name="Text">Its text.</param>
public sealed record GeneratedSource(string Path, string Text);

/// <summary>A resource to compile into an assembly, such as a WPF app's <c>.g.resources</c>.</summary>
/// <param name="Name">The resource's name in the assembly.</param>
/// <param name="Content">Its bytes.</param>
public sealed record VariantResource(string Name, ReadOnlyMemory<byte> Content);

/// <summary>
/// How to compile a project differently from the editor's live compilation: for a build that runs somewhere
/// else, such as a Windows app under Wine, which compiles against Windows' reference assemblies.
/// </summary>
public sealed record CompilationVariant
{
    /// <summary>
    /// The assemblies the project compiles against besides .NET's own reference assemblies, replacing its restored
    /// packages and any other references the editor gives it.
    /// </summary>
    public IReadOnlyList<string> References { get; init; } = [];

    /// <summary>The project's references, already built this way, replacing the editor's compilations of them.</summary>
    public IReadOnlyList<CompiledAssembly> ProjectReferences { get; init; } = [];

    /// <summary>Generated C# files; one with the path of a file the project already has replaces it.</summary>
    public IReadOnlyList<GeneratedSource> Sources { get; init; } = [];

    /// <summary>Resources to compile in besides the project's own embedded resources.</summary>
    public IReadOnlyList<VariantResource> Resources { get; init; } = [];

    /// <summary>Preprocessor symbols to define besides the configuration's, such as <c>WINDOWS</c>.</summary>
    public IReadOnlyList<string> PreprocessorSymbols { get; init; } = [];
}

/// <summary>
/// Variants of a project's compilation for builds that run elsewhere, and C# files generated by build steps outside
/// Roslyn, which the editor sees as generated documents.
/// </summary>
public sealed partial class RoslynWorkspaceHost
{
    /// <summary>The generated sources of each project, by project file path, kept across reloads.</summary>
    private readonly Dictionary<string, IReadOnlyList<GeneratedSource>> _generatedSources = new(StringComparer.Ordinal);

    /// <summary>
    /// Sets the C# files a build step generated for a project, such as WPF's markup compiler, replacing the ones it
    /// had before. They take part in diagnostics and IntelliSense as generated documents.
    /// </summary>
    /// <param name="projectFilePath">Full path of the project file. The project does not have to be loaded yet.</param>
    /// <param name="sources">The files.</param>
    public void SetGeneratedSources(string projectFilePath, IReadOnlyList<GeneratedSource> sources)
    {
        ArgumentException.ThrowIfNullOrEmpty(projectFilePath);
        ArgumentNullException.ThrowIfNull(sources);
        lock (_gate)
        {
            var previous = _generatedSources.GetValueOrDefault(projectFilePath) ?? [];
            _generatedSources[projectFilePath] = sources;
            if (!_projectIds.TryGetValue(projectFilePath, out var id))
            {
                return;
            }

            var solution = _workspace.CurrentSolution;
            foreach (var old in previous.Where(p => sources.All(s => s.Path != p.Path)))
            {
                if (_documents.Remove(old.Path, out var documentId))
                {
                    solution = solution.RemoveDocument(documentId);
                }
            }

            foreach (var source in sources)
            {
                if (_documents.TryGetValue(source.Path, out var documentId) && solution.GetDocument(documentId) is not null)
                {
                    solution = solution.WithDocumentText(documentId, Microsoft.CodeAnalysis.Text.SourceText.From(source.Text, Encoding.UTF8));
                }
                else
                {
                    documentId = DocumentId.CreateNewId(id, source.Path);
                    solution = solution.AddDocument(CreateDocumentInfo(documentId, source.Path, source.Text, isGenerated: true));
                    _documents[source.Path] = documentId;
                }
            }

            _workspace.TryApplyChanges(solution);
        }
    }

    /// <summary>
    /// Compiles one loaded project into memory as a variant: against other references, with generated files and
    /// resources added, for a program that runs outside TabStudio, so without the in-process safety checks.
    /// </summary>
    /// <param name="projectFilePath">Full path of the project file.</param>
    /// <param name="variant">How the compilation differs from the editor's.</param>
    /// <param name="cancellationToken">Cancels compilation.</param>
    /// <exception cref="ArgumentException">The project is not loaded.</exception>
    public async Task<CompilationResult> EmitVariantAsync(string projectFilePath, CompilationVariant variant, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(variant);
        var stopwatch = Stopwatch.StartNew();
        Project project;
        TsProject info;
        List<MetadataReference> references;
        lock (_gate)
        {
            if (!_projectIds.TryGetValue(projectFilePath, out var id))
            {
                throw new ArgumentException($"The project '{projectFilePath}' is not loaded.", nameof(projectFilePath));
            }

            project = _workspace.CurrentSolution.GetProject(id)!;
            info = _projects[id];
            references = [.. _frameworkReferences, .. variant.References.Distinct(StringComparer.Ordinal).Select(GetOrCreatePackageReference)];
        }

        references.AddRange(variant.ProjectReferences.Select(assembly => MetadataReference.CreateFromImage(assembly.Image, filePath: assembly.Name + ".dll")));
        var compilation = await project.GetCompilationAsync(cancellationToken).ConfigureAwait(false)
            ?? throw new InvalidOperationException($"Roslyn could not create a compilation for '{info.Name}'.");
        compilation = compilation.WithReferences(references);

        var parseOptions = (CSharpParseOptions)project.ParseOptions!;
        if (variant.PreprocessorSymbols.Count > 0)
        {
            parseOptions = parseOptions.WithPreprocessorSymbols(parseOptions.PreprocessorSymbolNames.Concat(variant.PreprocessorSymbols).Distinct(StringComparer.Ordinal));
            var reparsed = compilation.SyntaxTrees.Select(tree => CSharpSyntaxTree.ParseText(tree.GetText(cancellationToken), parseOptions, tree.FilePath, cancellationToken));
            compilation = compilation.RemoveAllSyntaxTrees().AddSyntaxTrees(reparsed);
        }

        if (variant.Sources.Count > 0)
        {
            var replaced = variant.Sources.Select(s => s.Path).ToHashSet(StringComparer.Ordinal);
            compilation = compilation
                .RemoveSyntaxTrees(compilation.SyntaxTrees.Where(tree => replaced.Contains(tree.FilePath)))
                .AddSyntaxTrees(variant.Sources.Select(source => CSharpSyntaxTree.ParseText(source.Text, parseOptions, source.Path, Encoding.UTF8, cancellationToken)));
        }

        var resources = ManifestResources.For(info)
            .Concat(variant.Resources.Select(resource => new ResourceDescription(resource.Name, () => new MemoryStream(resource.Content.ToArray(), writable: false), isPublic: true)));
        return CSharpCompiler.Emit(compilation, checkInProcessSafety: false, stopwatch, info.Name, resources, cancellationToken);
    }

    /// <summary>The generated documents of a project, for <see cref="CreateProjectInfo"/>. The caller holds the gate.</summary>
    private IEnumerable<DocumentInfo> GeneratedSourceDocuments(ProjectId id, TsProject project)
    {
        foreach (var source in _generatedSources.GetValueOrDefault(project.FilePath) ?? [])
        {
            var documentId = DocumentId.CreateNewId(id, source.Path);
            _documents[source.Path] = documentId;
            yield return CreateDocumentInfo(documentId, source.Path, source.Text, isGenerated: true);
        }
    }
}
