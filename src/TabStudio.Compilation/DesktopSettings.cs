using TsProject = TabStudio.Core.Workspaces.ProjectInfo;

namespace TabStudio.Compilation;

/// <summary>
/// The application settings of WPF and Windows Forms apps: the <c>Settings</c> class Visual Studio generates from
/// <c>Properties/Settings.settings</c> derives from <c>System.Configuration.ApplicationSettingsBase</c>, which the
/// .NET Framework has in <c>System.dll</c> and the Windows desktop has in <c>System.Configuration.ConfigurationManager</c>,
/// and which neither OpenSilver nor TabStudio's Forms layer has. TabStudio compiles such a project with a small
/// <c>ApplicationSettingsBase</c> of its own, internal to the project: a setting starts with its
/// <c>DefaultSettingValue</c> and keeps what the app sets for as long as it runs.
/// </summary>
public static class DesktopSettings
{
    /// <summary>The file name of the generated settings class Visual Studio's settings designer writes.</summary>
    public const string SettingsDesignerFileName = "Settings.Designer.cs";

    /// <summary>
    /// Whether a project gets TabStudio's <c>ApplicationSettingsBase</c>: a WPF or Windows Forms project that compiles a
    /// <c>Settings.Designer.cs</c> and does not reference the package that has the real one.
    /// </summary>
    /// <param name="project">The project.</param>
    /// <param name="sourceFiles">The source files it compiles.</param>
    public static bool Applies(TsProject project, IEnumerable<string> sourceFiles)
    {
        ArgumentNullException.ThrowIfNull(project);
        ArgumentNullException.ThrowIfNull(sourceFiles);
        return (Wpf.WpfProject.UsesWpf(project) || WindowsForms.WindowsFormsProject.UsesWindowsForms(project))
            && !project.HasPackage("System.Configuration.ConfigurationManager")
            && sourceFiles.Any(f => string.Equals(Path.GetFileName(f), SettingsDesignerFileName, StringComparison.OrdinalIgnoreCase));
    }

    /// <summary>The source of TabStudio's <c>System.Configuration</c> settings types.</summary>
    public const string Source = """
        // <auto-generated>
        //     Generated by TabStudio: the System.Configuration settings types that a Settings.Designer.cs uses, for a
        //     WPF or Windows Forms app that runs on this device. Settings start with their default values and keep what
        //     the app sets while it runs.
        // </auto-generated>
        #nullable disable
        #pragma warning disable

        namespace System.Configuration
        {
            internal enum SpecialSetting { ConnectionString, WebServiceUrl }

            internal enum SettingsSerializeAs { String, Xml, Binary, ProviderSpecific }

            internal enum SettingsManageability { Roaming }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property)]
            internal sealed class UserScopedSettingAttribute : global::System.Attribute { }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property)]
            internal sealed class ApplicationScopedSettingAttribute : global::System.Attribute { }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property)]
            internal sealed class DefaultSettingValueAttribute : global::System.Attribute
            {
                public DefaultSettingValueAttribute(string value) => Value = value;

                public string Value { get; }
            }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Class)]
            internal sealed class SpecialSettingAttribute : global::System.Attribute
            {
                public SpecialSettingAttribute(SpecialSetting specialSetting) => SpecialSetting = specialSetting;

                public SpecialSetting SpecialSetting { get; }
            }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Class)]
            internal sealed class SettingsSerializeAsAttribute : global::System.Attribute
            {
                public SettingsSerializeAsAttribute(SettingsSerializeAs serializeAs) => SerializeAs = serializeAs;

                public SettingsSerializeAs SerializeAs { get; }
            }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Class)]
            internal sealed class SettingsDescriptionAttribute : global::System.Attribute
            {
                public SettingsDescriptionAttribute(string description) => Description = description;

                public string Description { get; }
            }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Class)]
            internal sealed class SettingsGroupNameAttribute : global::System.Attribute
            {
                public SettingsGroupNameAttribute(string groupName) => GroupName = groupName;

                public string GroupName { get; }
            }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Class)]
            internal sealed class SettingsManageabilityAttribute : global::System.Attribute
            {
                public SettingsManageabilityAttribute(SettingsManageability manageability) => Manageability = manageability;

                public SettingsManageability Manageability { get; }
            }

            [global::System.AttributeUsage(global::System.AttributeTargets.Property | global::System.AttributeTargets.Class)]
            internal sealed class NoSettingsVersionUpgradeAttribute : global::System.Attribute { }

            internal class SettingChangingEventArgs : global::System.ComponentModel.CancelEventArgs
            {
                public SettingChangingEventArgs(string settingName, string settingClass, string settingKey, object newValue, bool cancel)
                    : base(cancel)
                {
                    SettingName = settingName;
                    SettingClass = settingClass;
                    SettingKey = settingKey;
                    NewValue = newValue;
                }

                public string SettingName { get; }

                public string SettingClass { get; }

                public string SettingKey { get; }

                public object NewValue { get; }
            }

            internal delegate void SettingChangingEventHandler(object sender, SettingChangingEventArgs e);

            internal class SettingsLoadedEventArgs : global::System.EventArgs { }

            internal delegate void SettingsLoadedEventHandler(object sender, SettingsLoadedEventArgs e);

            internal delegate void SettingsSavingEventHandler(object sender, global::System.ComponentModel.CancelEventArgs e);

            internal abstract class SettingsBase
            {
                private readonly global::System.Collections.Generic.Dictionary<string, object> _values = new();

                public virtual object this[string propertyName]
                {
                    get
                    {
                        lock (_values)
                        {
                            if (!_values.TryGetValue(propertyName, out var value))
                            {
                                value = DefaultValue(propertyName);
                                _values[propertyName] = value;
                            }

                            return value;
                        }
                    }

                    set
                    {
                        lock (_values)
                        {
                            _values[propertyName] = value;
                        }
                    }
                }

                public bool IsSynchronized => true;

                public static SettingsBase Synchronized(SettingsBase settingsBase) => settingsBase;

                public virtual void Save()
                {
                }

                /// <summary>Forgets what the app set, so every setting has its default value again.</summary>
                protected void Clear()
                {
                    lock (_values)
                    {
                        _values.Clear();
                    }
                }

                private object DefaultValue(string propertyName)
                {
                    var property = GetType().GetProperty(propertyName, global::System.Reflection.BindingFlags.Instance | global::System.Reflection.BindingFlags.Public | global::System.Reflection.BindingFlags.NonPublic);
                    if (property is null)
                    {
                        return null;
                    }

                    var type = property.PropertyType;
                    var text = ((DefaultSettingValueAttribute)global::System.Attribute.GetCustomAttribute(property, typeof(DefaultSettingValueAttribute)))?.Value;
                    if (text is null)
                    {
                        return type.IsValueType ? global::System.Activator.CreateInstance(type) : null;
                    }

                    if (type == typeof(string))
                    {
                        return text;
                    }

                    try
                    {
                        return global::System.ComponentModel.TypeDescriptor.GetConverter(type).ConvertFromInvariantString(text);
                    }
                    catch (global::System.Exception)
                    {
                        return type.IsValueType ? global::System.Activator.CreateInstance(type) : null;
                    }
                }
            }

            internal abstract class ApplicationSettingsBase : SettingsBase, global::System.ComponentModel.INotifyPropertyChanged
            {
                protected ApplicationSettingsBase()
                {
                }

                protected ApplicationSettingsBase(string settingsKey) => SettingsKey = settingsKey;

                public event global::System.ComponentModel.PropertyChangedEventHandler PropertyChanged;

                public event SettingChangingEventHandler SettingChanging;

                public event SettingsLoadedEventHandler SettingsLoaded;

                public event SettingsSavingEventHandler SettingsSaving;

                public string SettingsKey { get; set; } = string.Empty;

                public override object this[string propertyName]
                {
                    get => base[propertyName];
                    set
                    {
                        var changing = new SettingChangingEventArgs(propertyName, GetType().FullName, SettingsKey, value, false);
                        OnSettingChanging(this, changing);
                        if (!changing.Cancel)
                        {
                            base[propertyName] = value;
                            OnPropertyChanged(this, new global::System.ComponentModel.PropertyChangedEventArgs(propertyName));
                        }
                    }
                }

                public object GetPreviousVersion(string propertyName) => null;

                public void Reload() => SettingsLoaded?.Invoke(this, new SettingsLoadedEventArgs());

                public void Reset() => Clear();

                public override void Save()
                {
                    var saving = new global::System.ComponentModel.CancelEventArgs();
                    OnSettingsSaving(this, saving);
                }

                public virtual void Upgrade()
                {
                }

                protected virtual void OnPropertyChanged(object sender, global::System.ComponentModel.PropertyChangedEventArgs e) => PropertyChanged?.Invoke(sender, e);

                protected virtual void OnSettingChanging(object sender, SettingChangingEventArgs e) => SettingChanging?.Invoke(sender, e);

                protected virtual void OnSettingsLoaded(object sender, SettingsLoadedEventArgs e) => SettingsLoaded?.Invoke(sender, e);

                protected virtual void OnSettingsSaving(object sender, global::System.ComponentModel.CancelEventArgs e) => SettingsSaving?.Invoke(sender, e);
            }
        }
        """;
}
