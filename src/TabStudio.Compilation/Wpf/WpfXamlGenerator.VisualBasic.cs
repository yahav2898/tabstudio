using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using TabStudio.Compilation.Wpf.Xaml;
using RoslynCompilation = Microsoft.CodeAnalysis.Compilation;

namespace TabStudio.Compilation.Wpf;

/// <summary>
/// The first pass for a WPF project in Visual Basic, which OpenSilver's XAML compiler also builds: the same classes,
/// fields and <c>Main</c> as for C#, in Visual Basic. An <c>x:Class</c> is relative to the project's root namespace,
/// as the Visual Basic compiler places every type.
/// </summary>
public sealed partial class WpfXamlGenerator
{
    /// <summary>The partial class of one XAML file, in Visual Basic.</summary>
    private static string GenerateVisualBasicClass(XamlClassFile file, XamlTypeSystem types)
    {
        var (ns, name) = Split(file.ClassName!);
        var baseType = types.FindType(file.RootNamespace, file.RootName) is { } root ? Display(root) : null;
        var fallback = types.Compilation.GetTypeByMetadataName("System.Windows.FrameworkElement") is { } element ? Display(element) : "Object";

        var text = new StringBuilder();
        text.Append(CultureInfo.InvariantCulture, $"""
            ' <auto-generated>
            '     Generated by TabStudio from {file.RelativePath}, as OpenSilver's XAML compiler does before the Visual Basic compiler:
            '     the class's named elements and InitializeComponent. Building the project replaces it with what OpenSilver's
            '     compiler generates after the Visual Basic compiler.
            ' </auto-generated>


            """);
        if (ns is not null)
        {
            text.Append(CultureInfo.InvariantCulture, $"Namespace {ns}\n");
        }

        text.Append(CultureInfo.InvariantCulture, $"{VisualBasicModifier(file.ClassModifier)} Partial Class [{name}]\n");
        if (baseType is not null)
        {
            text.Append(CultureInfo.InvariantCulture, $"    Inherits {baseType}\n\n");
        }

        foreach (var named in file.NamedElements)
        {
            var type = types.FindType(named.XmlNamespace, named.TypeName) is { } found ? Display(found) : fallback;
            text.Append(CultureInfo.InvariantCulture, $"    {VisualBasicModifier(named.Modifier)} WithEvents [{named.Name}] As {type}\n");
        }

        text.Append(CultureInfo.InvariantCulture, $"""

                Private _contentLoaded As Boolean

                ''' <summary>Builds the user interface its XAML describes.</summary>
                Public Sub InitializeComponent()
                    If _contentLoaded Then
                        Return
                    End If

                    _contentLoaded = True
                    Throw New Global.System.InvalidOperationException({VisualBasicString(file.RelativePath)} & " is compiled by OpenSilver's XAML compiler when TabStudio builds the project.")
                End Sub
            End Class

            """);
        if (ns is not null)
        {
            text.Append("End Namespace\n");
        }

        return text.ToString();
    }

    /// <summary>The application's <c>Main</c> and WPF API OpenSilver lacks, in Visual Basic, kept when the project builds.</summary>
    private static string? GenerateVisualBasicProjectCode(ImmutableArray<XamlClassFile?> files, RoslynCompilation compilation, string? outputType)
    {
        var types = XamlTypeSystem.For(compilation);
        if (types.Application is not { } application)
        {
            return null;
        }

        var head = new StringBuilder("""
            ' <auto-generated>
            '     Generated by TabStudio for a WPF project, which builds on OpenSilver: what the Windows Desktop SDK and WPF's
            '     markup compiler give it that OpenSilver does not.
            ' </auto-generated>

            Option Strict On
            Option Infer On
            Option Explicit On

            """);
        var body = new StringBuilder();

        var isExecutable = outputType is { } type && (type.Equals("WinExe", StringComparison.OrdinalIgnoreCase) || type.Equals("Exe", StringComparison.OrdinalIgnoreCase));
        if (files.FirstOrDefault(f => f is { Kind: XamlItemKind.ApplicationDefinition, ClassName: not null }) is { } app && isExecutable)
        {
            body.Append(VisualBasicApplicationClass(app, compilation, hasRun: !application.GetMembers("Run").IsEmpty));
        }

        if (NeedsNavigationWindow(compilation))
        {
            head.Append(CultureInfo.InvariantCulture, $"<Assembly: Global.System.Windows.Markup.XmlnsDefinition(\"{XamlNamespaces.Presentation}\", \"System.Windows.Navigation\")>\n");
        }

        body.Append(VisualBasicCompatibility(compilation, application));
        return body.Length == 0 ? null : head.Append(body).ToString();
    }

    /// <summary>The application class's <c>Main</c>, and its constructor when it has none, in Visual Basic.</summary>
    private static string VisualBasicApplicationClass(XamlClassFile app, RoslynCompilation compilation, bool hasRun)
    {
        var (ns, name) = Split(app.ClassName!);
        var metadataName = VisualBasicMetadataName(compilation, app.ClassName!);
        var declared = compilation.GetTypeByMetadataName(metadataName);
        var hasConstructor = declared?.InstanceConstructors.Any(c => !c.IsImplicitlyDeclared) == true;
        var type = Display(declared) ?? "Global." + metadataName;
        var run = hasRun ? "tabStudioApplication.Run()" : "Global.System.Windows.TabStudioApplicationExtensions.Run(tabStudioApplication)";

        var text = new StringBuilder("\n");
        if (ns is not null)
        {
            text.Append(CultureInfo.InvariantCulture, $"Namespace {ns}\n");
        }

        text.Append(CultureInfo.InvariantCulture, $"{VisualBasicModifier(app.ClassModifier)} Partial Class [{name}]\n");
        if (!hasConstructor)
        {
            text.Append("""
                    ''' <summary>Creates the application.</summary>
                    Public Sub New()
                    End Sub


                """);
        }

        text.Append(CultureInfo.InvariantCulture, $"""
                ''' <summary>Application Entry Point.</summary>
                <Global.System.STAThreadAttribute()>
                Public Shared Sub Main()
                    Dim tabStudioApplication As New {type}()
                    tabStudioApplication.InitializeComponent()
                    {run}
                End Sub
            End Class

            """);
        if (ns is not null)
        {
            text.Append("End Namespace\n");
        }

        return text.ToString();
    }

    /// <summary>What <see cref="Compatibility"/> and the navigation code add for C#, in Visual Basic.</summary>
    private static string VisualBasicCompatibility(RoslynCompilation compilation, INamedTypeSymbol application)
    {
        var text = new StringBuilder();
        if (compilation.GetTypeByMetadataName("System.Windows.ResourceDictionaryLocation") is null)
        {
            text.Append("""

                    ''' <summary>Where theme dictionaries are, for <see cref="ThemeInfoAttribute"/>.</summary>
                    Friend Enum ResourceDictionaryLocation
                        None = 0
                        SourceAssembly = 1
                        ExternalAssembly = 2
                    End Enum

                """);
        }

        if (compilation.GetTypeByMetadataName("System.Windows.ThemeInfoAttribute") is null)
        {
            text.Append("""

                    ''' <summary>Where an assembly's theme dictionaries are, as WPF's attribute says.</summary>
                    <Global.System.AttributeUsage(Global.System.AttributeTargets.Assembly)>
                    Friend NotInheritable Class ThemeInfoAttribute
                        Inherits Global.System.Attribute

                        Private ReadOnly _themeDictionaryLocation As ResourceDictionaryLocation
                        Private ReadOnly _genericDictionaryLocation As ResourceDictionaryLocation

                        Public Sub New(themeDictionaryLocation As ResourceDictionaryLocation, genericDictionaryLocation As ResourceDictionaryLocation)
                            _themeDictionaryLocation = themeDictionaryLocation
                            _genericDictionaryLocation = genericDictionaryLocation
                        End Sub

                        Public ReadOnly Property ThemeDictionaryLocation As ResourceDictionaryLocation
                            Get
                                Return _themeDictionaryLocation
                            End Get
                        End Property

                        Public ReadOnly Property GenericDictionaryLocation As ResourceDictionaryLocation
                            Get
                                Return _genericDictionaryLocation
                            End Get
                        End Property
                    End Class

                """);
        }

        if (application.GetMembers("Run").IsEmpty)
        {
            text.Append(CultureInfo.InvariantCulture, $"""

                    ''' <summary>WPF's <c>Application.Run</c>, for apps that run in the browser on OpenSilver.</summary>
                    Friend Module TabStudioApplicationExtensions
                        ''' <summary>Runs the application; in the browser OpenSilver keeps it running, so this returns at once.</summary>
                        <Global.System.Runtime.CompilerServices.Extension()>
                        Public Function Run(application As Global.System.Windows.Application) As Integer
                            Return 0
                        End Function

                        ''' <summary>Runs the application with a window as its main window, which TabStudio shows in the web preview.</summary>
                        <Global.System.Runtime.CompilerServices.Extension()>
                        Public Function Run(application As Global.System.Windows.Application, window As Global.System.Windows.Window) As Integer
                            Global.System.AppContext.SetData("{MainWindowKey}", window)
                            Return 0
                        End Function
                    End Module

                """);
        }

        if (NeedsNavigationWindow(compilation))
        {
            text.Append(VisualBasicNavigation);
        }

        return text.Length == 0 ? string.Empty : "\nNamespace Global.System.Windows\n" + text + "End Namespace\n";
    }

    /// <summary>The Visual Basic of <c>NavigationWindow</c>, its content loader and <c>Navigate(object)</c>, as <see cref="NavigationCompatibility"/> writes them in C#.</summary>
    private const string VisualBasicNavigation = """

            ''' <summary>WPF's <c>NavigationService.Navigate(object)</c>, which OpenSilver's NavigationService does not have.</summary>
            Friend Module TabStudioNavigationServiceExtensions
                ''' <summary>Shows an object, such as a page made with New, in the frame the service navigates.</summary>
                <Global.System.Runtime.CompilerServices.Extension()>
                Public Function Navigate(navigationService As Global.System.Windows.Navigation.NavigationService, root As Object) As Boolean
                    Dim uri = TryCast(root, Global.System.Uri)
                    If uri IsNot Nothing Then
                        Return navigationService.Navigate(uri)
                    End If

                    Dim host = GetType(Global.System.Windows.Navigation.NavigationService).GetProperty("Host", Global.System.Reflection.BindingFlags.Instance Or Global.System.Reflection.BindingFlags.NonPublic Or Global.System.Reflection.BindingFlags.Public)
                    Dim frame = If(host Is Nothing, Nothing, TryCast(host.GetValue(navigationService), Global.System.Windows.Controls.Frame))
                    If frame IsNot Nothing AndAlso TypeOf frame.ContentLoader IsNot Global.System.Windows.Navigation.TabStudioNavigationContentLoader Then
                        frame.ContentLoader = New Global.System.Windows.Navigation.TabStudioNavigationContentLoader()
                    End If

                    Return navigationService.Navigate(Global.System.Windows.Navigation.TabStudioNavigationContentLoader.Register(root))
                End Function
            End Module

            Namespace Navigation
                ''' <summary>
                ''' WPF's navigation window, which OpenSilver does not have: a window that shows pages in a frame, the first
                ''' from Source, the next from Navigate or a page's NavigationService. Added by TabStudio.
                ''' </summary>
                Public Class NavigationWindow
                    Inherits Global.System.Windows.Window

                    ''' <summary>The page the window shows first.</summary>
                    Public Shared ReadOnly SourceProperty As Global.System.Windows.DependencyProperty = Global.System.Windows.DependencyProperty.Register(
                        "Source", GetType(Global.System.Uri), GetType(NavigationWindow), New Global.System.Windows.PropertyMetadata(Nothing, AddressOf OnSourceChanged))

                    Private ReadOnly _frame As New Global.System.Windows.Controls.Frame With {.ContentLoader = New TabStudioNavigationContentLoader()}

                    ''' <summary>Creates the window, with its frame as its content.</summary>
                    Public Sub New()
                        Content = _frame
                    End Sub

                    ''' <summary>The page the window shows first, as a path in the project such as HomePage.xaml.</summary>
                    Public Property Source As Global.System.Uri
                        Get
                            Return CType(GetValue(SourceProperty), Global.System.Uri)
                        End Get
                        Set(value As Global.System.Uri)
                            SetValue(SourceProperty, value)
                        End Set
                    End Property

                    ''' <summary>The address of the page shown now.</summary>
                    Public ReadOnly Property CurrentSource As Global.System.Uri
                        Get
                            Return _frame.CurrentSource
                        End Get
                    End Property

                    ''' <summary>Whether there is a page to go back to.</summary>
                    Public ReadOnly Property CanGoBack As Boolean
                        Get
                            Return _frame.CanGoBack
                        End Get
                    End Property

                    ''' <summary>Whether there is a page to go forward to.</summary>
                    Public ReadOnly Property CanGoForward As Boolean
                        Get
                            Return _frame.CanGoForward
                        End Get
                    End Property

                    ''' <summary>Whether WPF shows its back and forward buttons; the web preview's browser has its own.</summary>
                    Public Property ShowsNavigationUI As Boolean = True

                    ''' <summary>Goes back to the previous page.</summary>
                    Public Sub GoBack()
                        _frame.GoBack()
                    End Sub

                    ''' <summary>Goes forward to the next page.</summary>
                    Public Sub GoForward()
                        _frame.GoForward()
                    End Sub

                    ''' <summary>Shows the page at an address.</summary>
                    Public Overloads Function Navigate(source As Global.System.Uri) As Boolean
                        Return _frame.Navigate(TabStudioNavigationContentLoader.Resolve(source, Me.GetType().Assembly))
                    End Function

                    ''' <summary>Shows an object, such as a page made with New.</summary>
                    Public Overloads Function Navigate(content As Object) As Boolean
                        Dim uri = TryCast(content, Global.System.Uri)
                        If uri IsNot Nothing Then
                            Return Navigate(uri)
                        End If

                        Return _frame.Navigate(TabStudioNavigationContentLoader.Register(content))
                    End Function

                    Private Shared Sub OnSourceChanged(d As Global.System.Windows.DependencyObject, e As Global.System.Windows.DependencyPropertyChangedEventArgs)
                        Dim window = TryCast(d, NavigationWindow)
                        Dim uri = TryCast(e.NewValue, Global.System.Uri)
                        If window IsNot Nothing AndAlso uri IsNot Nothing Then
                            window._frame.Source = TabStudioNavigationContentLoader.Resolve(uri, window.GetType().Assembly)
                        End If
                    End Sub
                End Class

                ''' <summary>Loads what a navigation window goes to: an object it was given, or a page of the app from its XAML file.</summary>
                Friend NotInheritable Class TabStudioNavigationContentLoader
                    Implements Global.System.Windows.Navigation.INavigationContentLoader

                    Private Const Prefix As String = "/TabStudio.Navigation/"
                    Private Shared ReadOnly Contents As New Global.System.Collections.Generic.Dictionary(Of String, Object)(Global.System.StringComparer.Ordinal)
                    Private Shared _next As Integer
                    Private ReadOnly _pages As New Global.System.Windows.Navigation.PageResourceContentLoader()

                    ''' <summary>An address for an object to navigate to.</summary>
                    Public Shared Function Register(content As Object) As Global.System.Uri
                        _next += 1
                        Dim key = Prefix & _next.ToString(Global.System.Globalization.CultureInfo.InvariantCulture) & ".xaml"
                        Contents(key) = content
                        Return New Global.System.Uri(key, Global.System.UriKind.Relative)
                    End Function

                    ''' <summary>A WPF address of a page, as OpenSilver finds pages: in the app's assembly.</summary>
                    Public Shared Function Resolve(source As Global.System.Uri, appAssembly As Global.System.Reflection.Assembly) As Global.System.Uri
                        Dim path = source.OriginalString.Replace("\"c, "/"c)
                        Const pack As String = "pack://application:,,,"
                        If path.StartsWith(pack, Global.System.StringComparison.OrdinalIgnoreCase) Then
                            path = path.Substring(pack.Length)
                        End If

                        If path.StartsWith(Prefix, Global.System.StringComparison.Ordinal) Then
                            Return New Global.System.Uri(path, Global.System.UriKind.Relative)
                        End If

                        If path.IndexOf(";component/", Global.System.StringComparison.OrdinalIgnoreCase) >= 0 Then
                            Return New Global.System.Uri(If(path.StartsWith("/", Global.System.StringComparison.Ordinal), path, "/" & path), Global.System.UriKind.Relative)
                        End If

                        Return New Global.System.Uri("/" & appAssembly.GetName().Name & ";component/" & path.TrimStart("/"c), Global.System.UriKind.Relative)
                    End Function

                    Public Function CanLoad(targetUri As Global.System.Uri, currentUri As Global.System.Uri) As Boolean Implements Global.System.Windows.Navigation.INavigationContentLoader.CanLoad
                        Return Contents.ContainsKey(KeyOf(targetUri)) OrElse _pages.CanLoad(targetUri, currentUri)
                    End Function

                    Public Function BeginLoad(targetUri As Global.System.Uri, currentUri As Global.System.Uri, userCallback As Global.System.AsyncCallback, asyncState As Object) As Global.System.IAsyncResult Implements Global.System.Windows.Navigation.INavigationContentLoader.BeginLoad
                        Dim content As Object = Nothing
                        If Not Contents.TryGetValue(KeyOf(targetUri), content) Then
                            Return _pages.BeginLoad(targetUri, currentUri, userCallback, asyncState)
                        End If

                        Dim result As New Loaded(asyncState, content)
                        Global.System.Windows.Threading.Dispatcher.CurrentDispatcher.BeginInvoke(
                            Sub()
                                If userCallback IsNot Nothing Then
                                    userCallback(result)
                                End If
                            End Sub)
                        Return result
                    End Function

                    Public Function EndLoad(asyncResult As Global.System.IAsyncResult) As Global.System.Windows.Navigation.LoadResult Implements Global.System.Windows.Navigation.INavigationContentLoader.EndLoad
                        Dim loaded = TryCast(asyncResult, Loaded)
                        Return If(loaded IsNot Nothing, New Global.System.Windows.Navigation.LoadResult(loaded.Content), _pages.EndLoad(asyncResult))
                    End Function

                    Public Sub CancelLoad(asyncResult As Global.System.IAsyncResult) Implements Global.System.Windows.Navigation.INavigationContentLoader.CancelLoad
                        If TypeOf asyncResult IsNot Loaded Then
                            _pages.CancelLoad(asyncResult)
                        End If
                    End Sub

                    Private Shared Function KeyOf(uri As Global.System.Uri) As String
                        Dim text = If(uri.IsAbsoluteUri, uri.AbsolutePath, uri.OriginalString)
                        Dim [end] = text.IndexOfAny(New Char() {"?"c, "#"c})
                        Return If([end] < 0, text, text.Substring(0, [end]))
                    End Function

                    Private NotInheritable Class Loaded
                        Implements Global.System.IAsyncResult

                        Private ReadOnly _state As Object
                        Private ReadOnly _content As Object

                        Public Sub New(asyncState As Object, content As Object)
                            _state = asyncState
                            _content = content
                        End Sub

                        Public ReadOnly Property Content As Object
                            Get
                                Return _content
                            End Get
                        End Property

                        Public ReadOnly Property AsyncState As Object Implements Global.System.IAsyncResult.AsyncState
                            Get
                                Return _state
                            End Get
                        End Property

                        Public ReadOnly Property AsyncWaitHandle As Global.System.Threading.WaitHandle Implements Global.System.IAsyncResult.AsyncWaitHandle
                            Get
                                Return Nothing
                            End Get
                        End Property

                        Public ReadOnly Property CompletedSynchronously As Boolean Implements Global.System.IAsyncResult.CompletedSynchronously
                            Get
                                Return False
                            End Get
                        End Property

                        Public ReadOnly Property IsCompleted As Boolean Implements Global.System.IAsyncResult.IsCompleted
                            Get
                                Return True
                            End Get
                        End Property
                    End Class
                End Class
            End Namespace

        """;

    /// <summary>A class's full name in metadata: under the root namespace, where Visual Basic puts every type.</summary>
    private static string VisualBasicMetadataName(RoslynCompilation compilation, string className) =>
        compilation.Options is Microsoft.CodeAnalysis.VisualBasic.VisualBasicCompilationOptions { RootNamespace: { Length: > 0 } root }
            ? root + "." + className
            : className;

    private static (string? Namespace, string Name) Split(string className)
    {
        var dot = className.LastIndexOf('.');
        return dot < 0 ? (null, className) : (className[..dot], className[(dot + 1)..]);
    }

    private static string VisualBasicModifier(string modifier) => modifier switch
    {
        "public" => "Public",
        "private" => "Private",
        "protected" => "Protected",
        "protected internal" => "Protected Friend",
        _ => "Friend",
    };

    private static string VisualBasicString(string text) => "\"" + text.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
}
