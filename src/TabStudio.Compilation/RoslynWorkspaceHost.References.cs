using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using TabStudio.Core.Workspaces;
using TsProject = TabStudio.Core.Workspaces.ProjectInfo;

namespace TabStudio.Compilation;

// How projects see each other as the .NET SDK builds them: the projects they compile against, the assembly attributes
// the SDK generates (InternalsVisibleTo among them) and strong-name signing, which a friend assembly's key must match.
public sealed partial class RoslynWorkspaceHost
{
    private readonly Dictionary<string, TsProject> _projectsByPath = new(StringComparer.Ordinal);

    /// <summary>
    /// The projects a project compiles against, as the SDK passes them to the compiler: the projects it references
    /// whose assemblies it uses, and, transitively, the projects those reference. As in the SDK, a reference with
    /// <c>ReferenceOutputAssembly="false"</c> or <c>OutputItemType="Analyzer"</c> is a build dependency only, a
    /// reference with <c>PrivateAssets="all"</c> does not flow on to the projects above it, and
    /// <c>DisableTransitiveProjectReferences</c> keeps a project to its own references. The caller holds the gate.
    /// </summary>
    /// <param name="project">The project.</param>
    /// <returns>Full paths of the project files, nearest first.</returns>
    internal List<string> CompileReferencesOf(TsProject project)
    {
        var result = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal) { project.FilePath };
        var transitive = !IsTrue(project.GetProperty("DisableTransitiveProjectReferences"));
        var pending = new Queue<(TsProject Project, bool Direct)>();
        pending.Enqueue((project, true));
        while (pending.TryDequeue(out var current))
        {
            foreach (var path in current.Project.ProjectReferences)
            {
                var reference = current.Project.GetProjectReference(path);
                if (!reference.IsCompiledAgainst || (!current.Direct && reference.IsPrivate) || !seen.Add(path))
                {
                    continue;
                }

                result.Add(path);
                if (transitive && _projectsByPath.TryGetValue(path, out var next))
                {
                    pending.Enqueue((next, false));
                }
            }
        }

        return result;
    }

    /// <summary>
    /// The source of the assembly attributes the SDK generates into <c>AssemblyInfo.cs</c> from the project's
    /// <c>AssemblyAttribute</c> and <c>InternalsVisibleTo</c> items (see <see cref="AssemblyAttributeItems"/>), or
    /// <see langword="null"/> when it has none.
    /// </summary>
    /// <param name="project">The project.</param>
    public static string? CreateAssemblyAttributesSource(TsProject project)
    {
        ArgumentNullException.ThrowIfNull(project);
        if (project.AssemblyAttributes.Count == 0)
        {
            return null;
        }

        var builder = new StringBuilder("// <auto-generated/>\n");
        foreach (var attribute in project.AssemblyAttributes)
        {
            var name = attribute.TypeName.Contains('.', StringComparison.Ordinal) ? "global::" + attribute.TypeName : attribute.TypeName;
            var arguments = attribute.Arguments.Select(a =>
                (a.Name is null ? string.Empty : a.Name + " = ") + (a.IsLiteral ? a.Value : SymbolDisplay.FormatLiteral(a.Value, quote: true)));
            builder.Append("[assembly: ").Append(name).Append('(').AppendJoin(", ", arguments).Append(")]\n");
        }

        return builder.ToString();
    }

    /// <summary>
    /// Signs the project's assembly with its strong-name key, as the SDK does when <c>SignAssembly</c> is
    /// <c>true</c>: with <c>AssemblyOriginatorKeyFile</c>, publicly when <c>PublicSign</c> is set, delayed when
    /// <c>DelaySign</c> is. Its identity then carries the public key, which is what an
    /// <c>InternalsVisibleTo("Friend, PublicKey=...")</c> in another project is checked against.
    /// </summary>
    /// <param name="options">The project's compilation options.</param>
    /// <param name="project">The project.</param>
    internal static CompilationOptions WithStrongName(CompilationOptions options, TsProject project)
    {
        if (StrongNameKeyFile(project) is not { } keyFile)
        {
            return options;
        }

        options = options.WithCryptoKeyFile(keyFile).WithStrongNameProvider(new DesktopStrongNameProvider());
        if (IsTrue(project.GetProperty("PublicSign")))
        {
            options = options.WithPublicSign(true);
        }
        else if (IsTrue(project.GetProperty("DelaySign")))
        {
            options = options.WithDelaySign(true);
        }

        return options;
    }

    /// <summary>The full path of a signed project's key file, or <see langword="null"/> when it is not signed or the file is missing.</summary>
    /// <param name="project">The project.</param>
    internal static string? StrongNameKeyFile(TsProject project)
    {
        if (!IsTrue(project.GetProperty("SignAssembly")) || project.GetProperty("AssemblyOriginatorKeyFile") is not { Length: > 0 } keyFile)
        {
            return null;
        }

        var path = Path.GetFullPath(Path.Combine(project.DirectoryPath, keyFile.Trim().Replace('\\', Path.DirectorySeparatorChar)));
        return File.Exists(path) ? path : null;
    }

    /// <summary>Indexes the loaded projects by file. The caller holds the gate.</summary>
    private void IndexProjects()
    {
        _projectsByPath.Clear();
        foreach (var project in _projects.Values)
        {
            _projectsByPath[project.FilePath] = project;
        }
    }

    private static bool IsTrue(string? value) => string.Equals(value?.Trim(), "true", StringComparison.OrdinalIgnoreCase);
}
