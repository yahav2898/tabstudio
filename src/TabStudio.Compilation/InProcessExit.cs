using System.Reflection;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using VB = Microsoft.CodeAnalysis.VisualBasic;
using VBSyntax = Microsoft.CodeAnalysis.VisualBasic.Syntax;

namespace TabStudio.Compilation;

/// <summary>
/// Lets a C# or Visual Basic program that calls <see cref="Environment.Exit(int)"/> or <see cref="Environment.FailFast(string)"/> run
/// inside TabStudio: when a workspace's program is built to run, those calls are compiled as calls to
/// <c>TabStudio.Runtime.ProgramExit</c>, which ends the program by throwing <c>TabStudio.Runtime.ProgramExitException</c>
/// with its exit code. The program runner, and the Windows Forms layer for a handler, end the run with that code, as the
/// process would have ended; TabStudio itself keeps running. Visual Studio builds such a program without an error, and
/// so does TabStudio now.
/// </summary>
/// <remarks>
/// Only the calls are changed, on their own line, so the program's line numbers stay as they are. A program that catches
/// every exception around the call keeps running after it, where the process would have ended; that is the one
/// difference.
/// </remarks>
public static class InProcessExit
{
    /// <summary>The full name of the exception a redirected call throws, which runners recognize by name.</summary>
    public const string ExceptionTypeName = "TabStudio.Runtime.ProgramExitException";

    /// <summary>The path of the file the redirected calls go to, which a compilation gets when it has any.</summary>
    private const string ShimPath = "TabStudio.Runtime.ProgramExit.g.cs";

    /// <summary>The Visual Basic file the redirected calls go to. <c>Global</c> keeps it out of the project's root namespace.</summary>
    private const string VisualBasicShimPath = "TabStudio.Runtime.ProgramExit.g.vb";

    private const string VisualBasicShim = """
        ' <auto-generated>Added by TabStudio: Environment.Exit and FailFast end the program, which runs inside the IDE.</auto-generated>
        Option Strict On
        Namespace Global.TabStudio.Runtime
            Friend NotInheritable Class ProgramExit
                Private Sub New()
                End Sub

                Public Shared Sub [Exit](exitCode As Integer)
                    Throw New ProgramExitException(exitCode, Nothing)
                End Sub

                Public Shared Sub FailFast(message As String)
                    Throw New ProgramExitException(&H80131623, message)
                End Sub

                Public Shared Sub FailFast(message As String, exception As Global.System.Exception)
                    Throw New ProgramExitException(&H80131623, message)
                End Sub

                Public Shared Sub FailFast(message As String, exception As Global.System.Exception, errorMessage As String)
                    Throw New ProgramExitException(&H80131623, message)
                End Sub
            End Class

            Friend NotInheritable Class ProgramExitException
                Inherits Global.System.Exception

                Private ReadOnly _exitCode As Integer

                Public Sub New(exitCode As Integer, message As String)
                    MyBase.New(If(message, "The program called Environment.Exit(" & exitCode.ToString(Global.System.Globalization.CultureInfo.InvariantCulture) & ")."))
                    _exitCode = exitCode
                End Sub

                Public ReadOnly Property ExitCode As Integer
                    Get
                        Return _exitCode
                    End Get
                End Property
            End Class
        End Namespace
        """;

    private const string Shim = """
        // <auto-generated>Added by TabStudio: Environment.Exit and FailFast end the program, which runs inside the IDE.</auto-generated>
        #nullable enable
        namespace TabStudio.Runtime
        {
            internal static class ProgramExit
            {
                [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]
                public static void Exit(int exitCode) => throw new ProgramExitException(exitCode, null);

                [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]
                public static void FailFast(string? message) => throw new ProgramExitException(unchecked((int)0x80131623), message);

                [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]
                public static void FailFast(string? message, global::System.Exception? exception) => throw new ProgramExitException(unchecked((int)0x80131623), message);

                [global::System.Diagnostics.CodeAnalysis.DoesNotReturn]
                public static void FailFast(string? message, global::System.Exception? exception, string? errorMessage) => throw new ProgramExitException(unchecked((int)0x80131623), message);
            }

            internal sealed class ProgramExitException : global::System.Exception
            {
                public ProgramExitException(int exitCode, string? message)
                    : base(message ?? "The program called Environment.Exit(" + exitCode.ToString(global::System.Globalization.CultureInfo.InvariantCulture) + ").")
                {
                    ExitCode = exitCode;
                }

                public int ExitCode { get; }
            }
        }
        """;

    /// <summary>
    /// A compilation with its calls of <see cref="Environment.Exit(int)"/> and <see cref="Environment.FailFast(string)"/>
    /// going to <c>TabStudio.Runtime.ProgramExit</c> instead; the same compilation when it has none or is not C#.
    /// </summary>
    /// <param name="compilation">The program's compilation.</param>
    /// <param name="cancellationToken">Cancels the work.</param>
    public static Microsoft.CodeAnalysis.Compilation Redirect(Microsoft.CodeAnalysis.Compilation compilation, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(compilation);
        if (compilation is VB.VisualBasicCompilation basic)
        {
            return RedirectVisualBasic(basic, cancellationToken);
        }

        if (compilation is not CSharpCompilation csharp)
        {
            return compilation;
        }

        var result = csharp;
        var changed = false;
        foreach (var tree in csharp.SyntaxTrees)
        {
            var root = tree.GetRoot(cancellationToken);
            var candidates = root.DescendantNodes().OfType<InvocationExpressionSyntax>()
                .Where(i => i.Expression is MemberAccessExpressionSyntax { Name.Identifier.ValueText: "Exit" or "FailFast" })
                .ToList();
            if (candidates.Count == 0)
            {
                continue;
            }

            var model = csharp.GetSemanticModel(tree);
            var calls = candidates
                .Where(i => model.GetSymbolInfo(i, cancellationToken).Symbol is IMethodSymbol { ContainingType: { } type }
                    && type.ToDisplayString() == "System.Environment")
                .ToList();
            if (calls.Count == 0)
            {
                continue;
            }

            var rewritten = root.ReplaceNodes(calls.Select(c => c.Expression), (original, _) =>
            {
                var name = ((MemberAccessExpressionSyntax)original).Name.Identifier.ValueText;
                return SyntaxFactory.ParseExpression("global::TabStudio.Runtime.ProgramExit." + name).WithTriviaFrom(original);
            });
            // Parsed again from text with the original's encoding, which the PDB needs to embed the source.
            var text = SourceText.From(rewritten.ToFullString(), tree.Encoding ?? Encoding.UTF8);
            result = result.ReplaceSyntaxTree(tree, CSharpSyntaxTree.ParseText(text, (CSharpParseOptions)tree.Options, tree.FilePath, cancellationToken));
            changed = true;
        }

        if (!changed)
        {
            return compilation;
        }

        var options = (CSharpParseOptions)(csharp.SyntaxTrees.FirstOrDefault()?.Options ?? CSharpParseOptions.Default);
        return result.AddSyntaxTrees(CSharpSyntaxTree.ParseText(SourceText.From(Shim, Encoding.UTF8), options, ShimPath, cancellationToken));
    }

    /// <summary>
    /// The Visual Basic half of <see cref="Redirect"/>: a library such as Community.VisualBasic, whose
    /// <c>ProjectData.EndApp</c> calls <see cref="Environment.Exit(int)"/>, ends the program instead of closing TabStudio.
    /// Names compare without case, as Visual Basic's do; only calls that bind to <see cref="Environment"/> change.
    /// </summary>
    private static VB.VisualBasicCompilation RedirectVisualBasic(VB.VisualBasicCompilation basic, CancellationToken cancellationToken)
    {
        var result = basic;
        var changed = false;
        foreach (var tree in basic.SyntaxTrees)
        {
            var root = tree.GetRoot(cancellationToken);
            var candidates = root.DescendantNodes().OfType<VBSyntax.InvocationExpressionSyntax>()
                .Where(i => i.Expression is VBSyntax.MemberAccessExpressionSyntax { Name.Identifier.ValueText: var name }
                    && (string.Equals(name, "Exit", StringComparison.OrdinalIgnoreCase) || string.Equals(name, "FailFast", StringComparison.OrdinalIgnoreCase)))
                .ToList();
            if (candidates.Count == 0)
            {
                continue;
            }

            var model = basic.GetSemanticModel(tree);
            var calls = candidates
                .Select(i => (Call: i, Method: model.GetSymbolInfo(i, cancellationToken).Symbol as IMethodSymbol))
                .Where(c => c.Method?.ContainingType?.ToDisplayString() == "System.Environment")
                .ToList();
            if (calls.Count == 0)
            {
                continue;
            }

            var names = calls.ToDictionary(c => (SyntaxNode)c.Call.Expression!, c => c.Method!.Name);
            var rewritten = root.ReplaceNodes(names.Keys, (original, _) =>
                VB.SyntaxFactory.ParseExpression("Global.TabStudio.Runtime.ProgramExit." + names[original]).WithTriviaFrom(original));
            var text = SourceText.From(rewritten.ToFullString(), tree.Encoding ?? Encoding.UTF8);
            result = result.ReplaceSyntaxTree(tree, VB.VisualBasicSyntaxTree.ParseText(text, (VB.VisualBasicParseOptions)tree.Options, tree.FilePath, cancellationToken));
            changed = true;
        }

        if (!changed)
        {
            return basic;
        }

        var options = (VB.VisualBasicParseOptions)(basic.SyntaxTrees.FirstOrDefault()?.Options ?? VB.VisualBasicParseOptions.Default);
        return result.AddSyntaxTrees(VB.VisualBasicSyntaxTree.ParseText(SourceText.From(VisualBasicShim, Encoding.UTF8), options, VisualBasicShimPath, cancellationToken));
    }

    /// <summary>
    /// The exit code of a program that ended through a redirected call, when <paramref name="exception"/> (or the
    /// exception inside a <see cref="TargetInvocationException"/> or <see cref="AggregateException"/>) is the one it throws.
    /// </summary>
    /// <param name="exception">The exception the program ended with.</param>
    /// <param name="exitCode">Its exit code.</param>
    public static bool TryGetExitCode(Exception? exception, out int exitCode)
    {
        for (var current = exception; current is not null; current = current is TargetInvocationException or AggregateException ? current.InnerException : null)
        {
            if (current.GetType().FullName == ExceptionTypeName
                && current.GetType().GetProperty("ExitCode")?.GetValue(current) is int code)
            {
                exitCode = code;
                return true;
            }
        }

        exitCode = 0;
        return false;
    }
}
