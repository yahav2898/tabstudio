using System.Globalization;
using System.Text;
using TsProject = TabStudio.Core.Workspaces.ProjectInfo;

namespace TabStudio.Compilation.WindowsForms;

/// <summary>
/// What the Windows Desktop SDK adds to a project with <c>&lt;UseWindowsForms&gt;true&lt;/UseWindowsForms&gt;</c>, which
/// TabStudio adds itself: the global usings of <c>System.Drawing</c> and <c>System.Windows.Forms</c>, and the
/// <c>ApplicationConfiguration</c> class its source generator writes for an app's <c>Main</c> to call.
/// </summary>
/// <remarks>
/// A Windows Forms project compiles against TabStudio's Forms layer, which has the API of System.Windows.Forms and
/// System.Drawing, whatever its <c>TargetFramework</c> says, such as <c>net10.0-windows</c>.
/// </remarks>
public static class WindowsFormsProject
{
    /// <summary>The namespaces the Windows Desktop SDK imports for Windows Forms when <c>ImplicitUsings</c> is enabled.</summary>
    public static IReadOnlyList<string> ImplicitUsingNamespaces { get; } = ["System.Drawing", "System.Windows.Forms"];

    /// <summary>Whether a project uses Windows Forms.</summary>
    /// <param name="project">The project.</param>
    public static bool UsesWindowsForms(TsProject project)
    {
        ArgumentNullException.ThrowIfNull(project);
        return IsTrue(project.GetProperty("UseWindowsForms"));
    }

    /// <summary>
    /// Whether a project compiles against TabStudio's Forms layer: it uses Windows Forms, or it is a .NET Framework
    /// project that references System.Drawing without Windows Forms, as a game's library that draws for its Windows
    /// Forms app does (VBDev2Dev's Dots). On .NET 10 Graphics, Pen and Font are in no reference assembly, so such a
    /// library found none of them.
    /// </summary>
    /// <param name="project">The project.</param>
    public static bool UsesFormsLayer(TsProject project)
    {
        ArgumentNullException.ThrowIfNull(project);
        return UsesWindowsForms(project)
            || (!IsTrue(project.GetProperty("UseWPF"))
                && project.AssemblyReferences.Any(r => string.Equals(r.Name, "System.Drawing", StringComparison.OrdinalIgnoreCase)));
    }

    /// <summary>The global usings the SDK adds to a project for Windows Forms: none unless it uses it with implicit usings.</summary>
    /// <param name="project">The project.</param>
    public static IEnumerable<string> ImplicitUsings(TsProject project) =>
        project.ImplicitUsings && UsesWindowsForms(project) ? ImplicitUsingNamespaces : [];

    /// <summary>
    /// The source of the <c>ApplicationConfiguration</c> class the SDK's generator writes for a Windows Forms app,
    /// from the project's <c>ApplicationHighDpiMode</c>, <c>ApplicationVisualStyles</c>,
    /// <c>ApplicationUseCompatibleTextRendering</c> and <c>ApplicationDefaultFont</c> properties.
    /// </summary>
    /// <param name="project">The project.</param>
    /// <returns>The source, or <see langword="null"/> for a project that is not a Windows Forms app.</returns>
    /// <remarks>
    /// The class is in the global namespace, so <c>ApplicationConfiguration.Initialize()</c> finds it from Main in any
    /// namespace, or from top-level statements.
    /// </remarks>
    public static string? CreateApplicationConfigurationSource(TsProject project)
    {
        ArgumentNullException.ThrowIfNull(project);
        if (!UsesWindowsForms(project) || !project.IsExecutable)
        {
            return null;
        }

        var calls = new List<string>();
        if (!IsFalse(project.GetProperty("ApplicationVisualStyles")))
        {
            calls.Add("global::System.Windows.Forms.Application.EnableVisualStyles();");
        }

        var compatible = IsTrue(project.GetProperty("ApplicationUseCompatibleTextRendering")) ? "true" : "false";
        calls.Add($"global::System.Windows.Forms.Application.SetCompatibleTextRenderingDefault({compatible});");
        var dpiMode = project.GetProperty("ApplicationHighDpiMode") is { Length: > 0 } mode && IsIdentifier(mode.Trim()) ? mode.Trim() : "SystemAware";
        calls.Add($"global::System.Windows.Forms.Application.SetHighDpiMode(global::System.Windows.Forms.HighDpiMode.{dpiMode});");
        if (DefaultFont(project.GetProperty("ApplicationDefaultFont")) is { } font)
        {
            calls.Add($"global::System.Windows.Forms.Application.SetDefaultFont({font});");
        }

        var builder = new StringBuilder();
        builder.Append("// <auto-generated>\n//     Generated by TabStudio as the Windows Desktop SDK's ApplicationConfiguration generator does.\n// </auto-generated>\n\n");
        builder.Append("/// <summary>Bootstrap the application configuration.</summary>\n");
        builder.Append("[global::System.CodeDom.Compiler.GeneratedCode(\"System.Windows.Forms.Generators\", \"10.0.0.0\")]\n");
        builder.Append("internal static partial class ApplicationConfiguration\n{\n");
        builder.Append("    /// <summary>\n    ///  Bootstrap the application as follows:\n    ///  <code>\n");
        foreach (var call in calls)
        {
            builder.Append("    ///  ").Append(call.Replace("global::", string.Empty, StringComparison.Ordinal)).Append('\n');
        }

        builder.Append("    ///  </code>\n    /// </summary>\n    public static void Initialize()\n    {\n");
        foreach (var call in calls)
        {
            builder.Append("        ").Append(call).Append('\n');
        }

        builder.Append("    }\n}\n");
        return builder.ToString();
    }

    /// <summary>
    /// The font of <c>ApplicationDefaultFont</c>, such as <c>Microsoft Sans Serif, 8.25pt</c> or
    /// <c>Segoe UI, 10pt, style=Bold</c>, as C# that creates it.
    /// </summary>
    internal static string? DefaultFont(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return null;
        }

        var parts = value.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length < 2)
        {
            return null;
        }

        var sizeText = parts[1];
        var unit = "Point";
        foreach (var (suffix, name) in new[] { ("pt", "Point"), ("px", "Pixel"), ("em", "World") })
        {
            if (sizeText.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
            {
                sizeText = sizeText[..^suffix.Length];
                unit = name;
                break;
            }
        }

        if (!float.TryParse(sizeText, NumberStyles.Float, CultureInfo.InvariantCulture, out var size) || size <= 0)
        {
            return null;
        }

        var styles = parts.Skip(2)
            .Select(p => p.StartsWith("style=", StringComparison.OrdinalIgnoreCase) ? p[6..] : p)
            .SelectMany(p => p.Split(' ', StringSplitOptions.RemoveEmptyEntries))
            .Where(IsIdentifier)
            .Select(s => $"global::System.Drawing.FontStyle.{s}")
            .ToList();
        var style = styles.Count == 0 ? "global::System.Drawing.FontStyle.Regular" : string.Join(" | ", styles);
        var family = parts[0].Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);
        return $"new global::System.Drawing.Font(\"{family}\", {size.ToString("R", CultureInfo.InvariantCulture)}f, {style}, global::System.Drawing.GraphicsUnit.{unit})";
    }

    private static bool IsIdentifier(string text) => text.Length > 0 && char.IsLetter(text[0]) && text.All(char.IsLetterOrDigit);

    private static bool IsTrue(string? value) => string.Equals(value?.Trim(), "true", StringComparison.OrdinalIgnoreCase);

    private static bool IsFalse(string? value) => string.Equals(value?.Trim(), "false", StringComparison.OrdinalIgnoreCase);
}
