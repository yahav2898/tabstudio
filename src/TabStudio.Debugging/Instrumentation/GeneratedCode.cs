using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using VB = Microsoft.CodeAnalysis.VisualBasic;

namespace TabStudio.Debugging.Instrumentation;

/// <summary>Recognizes generated source files, which the debugger never instruments or stops in.</summary>
internal static class GeneratedCode
{
    private static readonly string[] GeneratedSuffixes =
    [
        ".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs",
        ".g.vb", ".g.i.vb", ".designer.vb", ".generated.vb",
    ];

    /// <summary>
    /// Whether a tree is generated: its file name ends like the SDK's generated files (such as
    /// <c>obj/App.GlobalUsings.g.cs</c> or <c>Form1.Designer.vb</c>), or it starts with an <c>&lt;auto-generated&gt;</c>
    /// comment.
    /// </summary>
    public static bool IsGenerated(SyntaxTree tree, CancellationToken cancellationToken)
    {
        var name = Path.GetFileName(tree.FilePath);
        if (GeneratedSuffixes.Any(suffix => name.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        var root = tree.GetRoot(cancellationToken);
        var visualBasic = root.Language == LanguageNames.VisualBasic;
        foreach (var trivia in root.GetLeadingTrivia())
        {
            var isComment = visualBasic
                ? trivia.RawKind == (int)VB.SyntaxKind.CommentTrivia
                : trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia);
            if (isComment && trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }
}
