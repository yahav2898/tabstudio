namespace TabStudio.Debugging.Instrumentation;

/// <summary>
/// The small runtime that instrumented programs call, added to their compilation as source, and the contract it
/// shares with the debugger.
/// </summary>
/// <remarks>
/// <para>
/// On Android an assembly loaded from memory has no file location, so a program cannot reference TabStudio's own
/// assemblies. Instead every debug build gets its own copy of <c>__TabStudioDebug</c>, an internal class that
/// reaches the debugger only through base library types: on first use it reads an <see cref="object"/> array from
/// <see cref="AppContext.GetData(string)"/> under <see cref="DataKey"/> and casts its entries to delegates.
/// </para>
/// <para>
/// The array holds <see cref="ContractVersion"/> followed by, in order: enter (<c>Func&lt;int, object?&gt;</c>),
/// exit, suspend and resume (<c>Action&lt;object?&gt;</c>), step (<c>Func&lt;object?, int, bool&gt;</c>), break
/// (<c>Action&lt;object?, int, object?[]?&gt;</c>) and fault (<c>Func&lt;object?, Exception, object?[]?, bool&gt;</c>).
/// Without that data every hook does nothing, so an instrumented program also runs normally on its own.
/// </para>
/// </remarks>
internal static class DebugRuntimeSource
{
    /// <summary>The <see cref="AppContext"/> data name the runtime reads its sink from.</summary>
    public const string DataKey = "TabStudio.Debugger";

    /// <summary>The runtime class, in the global namespace of the program.</summary>
    public const string ClassName = "__TabStudioDebug";

    /// <summary>The file name of the runtime's syntax tree. It ends in <c>.g.cs</c>, so it is never instrumented.</summary>
    public const string FilePath = "__TabStudioDebug.g.cs";

    /// <summary>The version of the sink layout, the first element of the sink array.</summary>
    public const int ContractVersion = 2;

    /// <summary>The number of elements in the sink array.</summary>
    public const int SinkLength = 9;

    /// <summary>The source of the runtime.</summary>
    public const string Text = """
        // <auto-generated/>
        // Added by the TabStudio debugger. Every hook forwards to the debugger through delegates found in AppContext
        // under "TabStudio.Debugger", so the program needs no reference to TabStudio. Without them, hooks do nothing.
        #nullable enable
        [global::System.Runtime.CompilerServices.CompilerGenerated]
        [global::System.Diagnostics.DebuggerNonUserCode]
        internal static class __TabStudioDebug
        {
            private static readonly global::System.Func<int, object?>? s_enter;
            private static readonly global::System.Action<object?>? s_exit;
            private static readonly global::System.Action<object?>? s_suspend;
            private static readonly global::System.Action<object?>? s_resume;
            private static readonly global::System.Func<object?, int, bool>? s_step;
            private static readonly global::System.Action<object?, int, object?[]?>? s_break;
            private static readonly global::System.Func<object?, global::System.Exception, object?[]?, bool>? s_fault;
            private static readonly global::System.Action<object?, int, string, object?>? s_write;

            static __TabStudioDebug()
            {
                if (global::System.AppContext.GetData("TabStudio.Debugger") is object[] sink && sink.Length == 9 && sink[0] is int version && version == 2)
                {
                    s_enter = sink[1] as global::System.Func<int, object?>;
                    s_exit = sink[2] as global::System.Action<object?>;
                    s_suspend = sink[3] as global::System.Action<object?>;
                    s_resume = sink[4] as global::System.Action<object?>;
                    s_step = sink[5] as global::System.Func<object?, int, bool>;
                    s_break = sink[6] as global::System.Action<object?, int, object?[]?>;
                    s_fault = sink[7] as global::System.Func<object?, global::System.Exception, object?[]?, bool>;
                    s_write = sink[8] as global::System.Action<object?, int, string, object?>;
                }
            }

            public static object? Enter(int methodId) => s_enter?.Invoke(methodId);

            public static bool IsRecording => s_write is not null;

            public static void Exit(object? frame) => s_exit?.Invoke(frame);

            public static void Suspend(object? frame) => s_suspend?.Invoke(frame);

            public static void Resume(object? frame) => s_resume?.Invoke(frame);

            public static bool Step(object? frame, int statementId) => s_step is not null && s_step(frame, statementId);

            public static void Break(object? frame, int statementId, object?[]? locals) => s_break?.Invoke(frame, statementId, locals);

            public static bool Fault(object? frame, global::System.Exception exception, object?[]? values) => s_fault is not null && s_fault(frame, exception, values);

            public static T Write<T>(object? frame, int site, string path, T value)
            {
                if (s_write is not null) s_write(frame, site, path, value);
                return value;
            }

            public static T PostWrite<T>(object? frame, int site, string path, T result, T value)
            {
                if (s_write is not null) s_write(frame, site, path, value);
                return result;
            }
        }
        """;
}
