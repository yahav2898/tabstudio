namespace TabStudio.Debugging.Instrumentation.VisualBasic;

/// <summary>
/// The debugger runtime of Visual Basic programs: the same <c>__TabStudioDebug</c> class, in the global namespace, and the
/// same sink contract as <see cref="DebugRuntimeSource"/>, written in Visual Basic so that it compiles into the
/// program's own assembly, as the C# runtime does into C# programs.
/// </summary>
/// <remarks>
/// <para>
/// The hooks are named so that none is a Visual Basic keyword (<c>Step</c>, <c>Exit</c> and <c>Resume</c> are). Every
/// statement hook is a single statement with no single-line <c>If</c>, because a single-line <c>If</c> would take the
/// statements that follow it on the line, separated by colons, into its <c>Then</c> part:
/// <c>Global.__TabStudioDebug.Hook(ShouldBreak(f, id) AndAlso BreakHere(f, id, locals))</c>. <c>AndAlso</c> only builds
/// the array of locals when the debugger stops there. <see cref="ConditionHook"/> does the same inside a loop or
/// <c>ElseIf</c> condition, and passes the condition's value through unchanged.
/// </para>
/// <para>
/// The file has its own <c>Option</c> statements, so it compiles the same whatever the project's options are, and
/// <c>Namespace Global</c> keeps it out of the project's root namespace.
/// </para>
/// </remarks>
internal static class VisualBasicRuntimeSource
{
    /// <summary>The file name of the runtime's syntax tree. It ends in <c>.g.vb</c>, so it is never instrumented.</summary>
    public const string FilePath = "__TabStudioDebug.g.vb";

    /// <summary>The fully qualified runtime class, as hooks call it.</summary>
    public const string Runtime = "Global." + DebugRuntimeSource.ClassName;

    /// <summary><c>EnterMethod(methodId) As Object</c>: the frame of a function that starts.</summary>
    public const string EnterMethod = "EnterMethod";

    /// <summary><c>ExitMethod(frame)</c>: the function is left, normally or by an exception.</summary>
    public const string ExitMethod = "ExitMethod";

    /// <summary><c>SuspendMethod(frame)</c>: an iterator is about to yield.</summary>
    public const string SuspendMethod = "SuspendMethod";

    /// <summary><c>ResumeMethod(frame)</c>: an iterator continues after a yield.</summary>
    public const string ResumeMethod = "ResumeMethod";

    /// <summary><c>ShouldBreak(frame, statementId) As Boolean</c>: whether the debugger wants the statement's locals.</summary>
    public const string ShouldBreak = "ShouldBreak";

    /// <summary><c>BreakHere(frame, statementId, locals) As Boolean</c>: pauses if needed; always returns <see langword="false"/>.</summary>
    public const string BreakHere = "BreakHere";

    /// <summary><c>Hook(reached As Boolean)</c>: does nothing; it makes the hook expression a statement.</summary>
    public const string StatementHook = "Hook";

    /// <summary><c>Condition(Of T)(reached As Boolean, value As T) As T</c>: returns the condition's value.</summary>
    public const string ConditionHook = "Condition";

    /// <summary><c>Fault(frame, exception, values) As Boolean</c>: the exception filter; always returns <see langword="false"/>.</summary>
    public const string Fault = "Fault";

    /// <summary>The source of the runtime.</summary>
    public const string Text = """
        ' <auto-generated/>
        ' Added by the TabStudio debugger. Every hook forwards to the debugger through delegates found in AppContext
        ' under "TabStudio.Debugger", so the program needs no reference to TabStudio. Without them, hooks do nothing.
        Option Strict On
        Option Explicit On
        Option Infer Off
        Option Compare Binary

        Namespace Global

            <Global.System.Runtime.CompilerServices.CompilerGenerated, Global.System.Diagnostics.DebuggerNonUserCode> Friend NotInheritable Class __TabStudioDebug
                Private Shared ReadOnly s_enter As Global.System.Func(Of Integer, Object)
                Private Shared ReadOnly s_exit As Global.System.Action(Of Object)
                Private Shared ReadOnly s_suspend As Global.System.Action(Of Object)
                Private Shared ReadOnly s_resume As Global.System.Action(Of Object)
                Private Shared ReadOnly s_step As Global.System.Func(Of Object, Integer, Boolean)
                Private Shared ReadOnly s_break As Global.System.Action(Of Object, Integer, Object())
                Private Shared ReadOnly s_fault As Global.System.Func(Of Object, Global.System.Exception, Object(), Boolean)

                Shared Sub New()
                    Dim sink As Object() = TryCast(Global.System.AppContext.GetData("TabStudio.Debugger"), Object())
                    If sink IsNot Nothing AndAlso sink.Length = 9 AndAlso TypeOf sink(0) Is Integer AndAlso DirectCast(sink(0), Integer) = 2 Then
                        s_enter = TryCast(sink(1), Global.System.Func(Of Integer, Object))
                        s_exit = TryCast(sink(2), Global.System.Action(Of Object))
                        s_suspend = TryCast(sink(3), Global.System.Action(Of Object))
                        s_resume = TryCast(sink(4), Global.System.Action(Of Object))
                        s_step = TryCast(sink(5), Global.System.Func(Of Object, Integer, Boolean))
                        s_break = TryCast(sink(6), Global.System.Action(Of Object, Integer, Object()))
                        s_fault = TryCast(sink(7), Global.System.Func(Of Object, Global.System.Exception, Object(), Boolean))
                    End If
                End Sub

                Private Sub New()
                End Sub

                Public Shared Function EnterMethod(methodId As Integer) As Object
                    Dim callback As Global.System.Func(Of Integer, Object) = s_enter
                    If callback Is Nothing Then Return Nothing
                    Return callback.Invoke(methodId)
                End Function

                Public Shared Sub ExitMethod(frame As Object)
                    Dim callback As Global.System.Action(Of Object) = s_exit
                    If callback IsNot Nothing Then callback.Invoke(frame)
                End Sub

                Public Shared Sub SuspendMethod(frame As Object)
                    Dim callback As Global.System.Action(Of Object) = s_suspend
                    If callback IsNot Nothing Then callback.Invoke(frame)
                End Sub

                Public Shared Sub ResumeMethod(frame As Object)
                    Dim callback As Global.System.Action(Of Object) = s_resume
                    If callback IsNot Nothing Then callback.Invoke(frame)
                End Sub

                Public Shared Function ShouldBreak(frame As Object, statementId As Integer) As Boolean
                    Dim callback As Global.System.Func(Of Object, Integer, Boolean) = s_step
                    If callback Is Nothing Then Return False
                    Return callback.Invoke(frame, statementId)
                End Function

                Public Shared Function BreakHere(frame As Object, statementId As Integer, locals As Object()) As Boolean
                    Dim callback As Global.System.Action(Of Object, Integer, Object()) = s_break
                    If callback IsNot Nothing Then callback.Invoke(frame, statementId, locals)
                    Return False
                End Function

                Public Shared Sub Hook(reached As Boolean)
                End Sub

                Public Shared Function Condition(Of T)(reached As Boolean, value As T) As T
                    Return value
                End Function

                Public Shared Function Fault(frame As Object, exception As Global.System.Exception, values As Object()) As Boolean
                    Dim callback As Global.System.Func(Of Object, Global.System.Exception, Object(), Boolean) = s_fault
                    If callback Is Nothing Then Return False
                    Return callback.Invoke(frame, exception, values)
                End Function
            End Class

        End Namespace
        """;
}
