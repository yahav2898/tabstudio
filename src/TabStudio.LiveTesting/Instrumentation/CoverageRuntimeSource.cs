using System.Globalization;

namespace TabStudio.LiveTesting.Instrumentation;

/// <summary>
/// The tiny runtime that coverage-instrumented code calls, added to each instrumented project as one more syntax
/// tree, and the contract it shares with <see cref="Coverage.CoverageRecorder"/>.
/// </summary>
/// <remarks>
/// <para>
/// Like the debugger's runtime, it reaches TabStudio only through base library types, because an assembly loaded
/// from memory on Android cannot reference TabStudio's own. On first use it reads an <see cref="object"/> array
/// from <see cref="AppContext.GetData(string)"/> under <see cref="DataKey"/>: <see cref="ContractVersion"/>, then the
/// recorder's <see cref="AsyncLocal{T}"/> of <c>bool[][]</c>, which holds the hit table of the test running on the
/// current thread of execution: one array per instrumented project, one element per coverage point.
/// </para>
/// <para>
/// A hit is two array reads and a write, with no lock and no call into TabStudio, so instrumented code stays
/// fast. Code that runs outside any test, or an assembly loaded without the recorder, records nothing.
/// </para>
/// <para>
/// It is separate from the debugger's <c>__TabStudioDebug</c>: a coverage build carries no debugger hooks and a
/// debug build no coverage hooks, so neither slows the other.
/// </para>
/// </remarks>
internal static class CoverageRuntimeSource
{
    /// <summary>The <see cref="AppContext"/> data name the runtime reads its sink from.</summary>
    public const string DataKey = "TabStudio.Coverage";

    /// <summary>The runtime class, in the global namespace of the instrumented project.</summary>
    public const string ClassName = "__TabStudioCoverage";

    /// <summary>The file name of the runtime's syntax tree. It ends in <c>.g.cs</c>, so it is never instrumented.</summary>
    public const string FilePath = "__TabStudioCoverage.g.cs";

    /// <summary>The version of the sink layout, the first element of the sink array.</summary>
    public const int ContractVersion = 1;

    /// <summary>The number of elements in the sink array.</summary>
    public const int SinkLength = 2;

    /// <summary>The source of the runtime for one instrumented project.</summary>
    /// <param name="module">The project's index in the hit table, which every hit of the project writes to.</param>
    public static string Text(int module) => Template.Replace("{MODULE}", module.ToString(CultureInfo.InvariantCulture), StringComparison.Ordinal);

    private const string Template = """
        // <auto-generated/>
        // Added by TabStudio's Live Unit Testing. Every hook marks a coverage point as hit in the table of the test
        // running on this thread of execution, found through AppContext under "TabStudio.Coverage". Without it, hooks do nothing.
        #nullable enable
        [global::System.Runtime.CompilerServices.CompilerGenerated]
        [global::System.Diagnostics.DebuggerNonUserCode]
        internal static class __TabStudioCoverage
        {
            private const int Module = {MODULE};
            private static readonly global::System.Threading.AsyncLocal<bool[][]>? s_current;

            static __TabStudioCoverage()
            {
                if (global::System.AppContext.GetData("TabStudio.Coverage") is object[] sink && sink.Length == 2 && sink[0] is int version && version == 1)
                {
                    s_current = sink[1] as global::System.Threading.AsyncLocal<bool[][]>;
                }
            }

            public static void Hit(int point)
            {
                if (s_current == null)
                {
                    return;
                }

                var table = s_current.Value;
                if (table != null && (uint)Module < (uint)table.Length)
                {
                    var hits = table[Module];
                    if (hits != null && (uint)point < (uint)hits.Length)
                    {
                        hits[point] = true;
                    }
                }
            }
        }
        """;
}
