using TabStudio.Toolchains.Processes;

namespace TabStudio.Toolchains.Embedded.Projects;

/// <summary>The native project system that owns an embedded build.</summary>
public enum EmbeddedProjectKind
{
    /// <summary>PlatformIO Core and platformio.ini.</summary>
    PlatformIO,
    /// <summary>Arduino CLI and a sketch folder.</summary>
    Arduino,
    /// <summary>Espressif's ESP-IDF build system.</summary>
    EspIdf,
    /// <summary>ST's generated Makefile or CMake project.</summary>
    Stm32Cube,
    /// <summary>Zephyr's west and CMake build.</summary>
    Zephyr,
    /// <summary>The Raspberry Pi Pico SDK.</summary>
    PicoSdk,
    /// <summary>Cargo with an embedded target and linker configuration.</summary>
    Rust,
    /// <summary>Python source deployed with mpremote.</summary>
    MicroPython,
    /// <summary>A vendor project requiring an explicit GCC import.</summary>
    VendorImport,
    /// <summary>An ARM GCC/CMake project generated by the vendor importer.</summary>
    GccCMakeArm,
    /// <summary>An AVR GCC/CMake project generated by the vendor importer.</summary>
    GccCMakeAvr,
}

/// <summary>A named build environment; values remain literal when the native project system expands them.</summary>
/// <param name="Name">The environment name.</param>
/// <param name="Board">A board identifier, if explicitly provided.</param>
/// <param name="Framework">The selected framework, if explicitly provided.</param>
public sealed record EmbeddedEnvironment(string Name, string? Board = null, string? Framework = null);

/// <summary>An embedded project detected without running repository code.</summary>
/// <param name="Kind">The build system.</param>
/// <param name="Directory">The absolute project directory.</param>
/// <param name="Marker">The relative marker path.</param>
/// <param name="Environments">Named build environments.</param>
/// <param name="DefaultEnvironment">An explicitly declared default environment.</param>
/// <param name="Target">An explicitly declared chip, target triple or board.</param>
/// <param name="Notes">Configuration that requires attention.</param>
public sealed record EmbeddedProject(EmbeddedProjectKind Kind, string Directory, string Marker,
    IReadOnlyList<EmbeddedEnvironment> Environments, string? DefaultEnvironment, string? Target,
    IReadOnlyList<string> Notes)
{
    /// <summary>The folder name shown in project selection.</summary>
    public string Name => Path.GetFileName(Directory.TrimEnd(Path.DirectorySeparatorChar));

    /// <summary>The absolute marker file.</summary>
    public string MarkerPath => Path.Combine(Directory, Marker);

    /// <summary>Whether PlatformIO must resolve default environments or extra configuration itself.</summary>
    public bool HasNativeEnvironmentSelection { get; init; }
}

/// <summary>Explicit device and build choices; no chip, pin map, port or board is guessed.</summary>
public sealed record EmbeddedBuildOptions
{
    /// <summary>A PlatformIO environment or Cube build configuration.</summary>
    public string? Environment { get; init; }

    /// <summary>The native build system's board identifier or Arduino FQBN.</summary>
    public string? Board { get; init; }

    /// <summary>The explicitly selected Arduino library example directory, relative to this project.</summary>
    public string? Sketch { get; init; }

    /// <summary>The embedded Rust target triple or ESP-IDF target.</summary>
    public string? Target { get; init; }

    /// <summary>The granted serial device path or network endpoint supplied by the device service.</summary>
    public string? Port { get; init; }

    /// <summary>An explicit probe-rs chip identifier.</summary>
    public string? Chip { get; init; }

    /// <summary>A built ELF, HEX or UF2 path, when its name cannot be inferred safely.</summary>
    public string? Firmware { get; init; }

    /// <summary>An optional explicit Zephyr runner.</summary>
    public string? Runner { get; init; }

    /// <summary>Limit parallel build workers on a tablet.</summary>
    public int Jobs { get; init; } = 2;

    /// <summary>Explicit PlatformIO package policy: native (default), or boxed-x86_64 only when no compatible ARM64 artifact exists.</summary>
    public string HostPackageMode { get; init; } = "native";
}

/// <summary>Native project commands that the existing process runtime can run without shell interpolation.</summary>
/// <param name="Preparation">Ordered configure commands.</param>
/// <param name="Build">Build commands; empty for interpreted board files.</param>
/// <param name="Upload">Upload commands, available only with sufficient explicit target information.</param>
/// <param name="ToolchainId">The Toolchain Store entry that supplies the project system.</param>
/// <param name="CompilationDatabase">The expected clangd compilation database, if the project emits one.</param>
/// <param name="Notes">Actionable prerequisites and limitations.</param>
public sealed record EmbeddedBuildPlan(IReadOnlyList<ProcessStartSpec> Preparation,
    IReadOnlyList<ProcessStartSpec> Build, IReadOnlyList<ProcessStartSpec> Upload, string ToolchainId,
    string? CompilationDatabase, IReadOnlyList<string> Notes);
